#!/usr/bin/env python3
"""Credits data of the Unity client from docs/CREDITS.md (the single source of truth, as for the main client and the website).

Reads the sections with the parser of client/tools/gen_credits.py and writes
  unity/Client/Assets/Chaos/Core/CreditsData.cs   CreditsData.All, the Credits window of the Unity client (CommunityExtras.cs CreditsPanel)

  python3 -I unity/tools/gen_unity_credits.py           # write the file
  python3 -I unity/tools/gen_unity_credits.py --check   # fail when it is not up to date (CI, unity-prototype.yml core job)

The C# file is UTF-8 and holds the text as written (the Unity client draws accents). Run python3 -I client/tools/gen_credits.py first when
docs/CREDITS.md changed: the three other outputs of that script are checked by tools/ci/check_credits.py.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'client', 'tools'))
import gen_credits  # noqa: E402

SOURCE = os.path.join(ROOT, 'docs', 'CREDITS.md')
OUT = os.path.join(ROOT, 'unity', 'Client', 'Assets', 'Chaos', 'Core', 'CreditsData.cs')
FIELDS = ('name', 'author', 'licence', 'credit', 'use', 'source')

HEAD = '''// Generated by unity/tools/gen_unity_credits.py from docs/CREDITS.md. Do not edit: edit docs/CREDITS.md and run
// python3 -I unity/tools/gen_unity_credits.py. A missing field is null.
namespace Chaos.Core
{
    public sealed class CreditEntry
    {
        public string Name, Author, Licence, Credit, Use, Source;
    }

    public sealed class CreditSection
    {
        public string Title, Pt, Note;
        public CreditEntry[] Entries;
    }

    public static class CreditsData
    {
        public static readonly CreditSection[] All =
        {
'''


def cs(text):
    """A C# string literal (regular, escaped)."""
    out = ['"']
    for ch in text:
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        elif ord(ch) < 32:
            out.append('\\u%04x' % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return ''.join(out)


def cs_data(sections):
    lines = [HEAD.rstrip('\n')]
    for s in sections:
        lines.append('            new CreditSection')
        lines.append('            {')
        lines.append('                Title = %s, Pt = %s, Note = %s,' % (cs(s['title']), cs(s['pt']), cs(s['note'])))
        lines.append('                Entries = new[]')
        lines.append('                {')
        for e in s['entries']:
            parts = ['%s = %s' % (k.capitalize(), cs(e[k])) for k in FIELDS if k in e]
            lines.append('                    new CreditEntry { ' + ', '.join(parts) + ' },')
        lines.append('                },')
        lines.append('            },')
    lines.append('        };')
    lines.append('    }')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def output(text):
    return cs_data(gen_credits.parse(text))


def main(argv):
    check = '--check' in argv
    try:
        with open(SOURCE, encoding='utf-8') as f:
            content = output(f.read())
    except gen_credits.CreditsError as e:
        print('gen_unity_credits: %s' % e)
        return 1
    old = None
    if os.path.exists(OUT):
        with open(OUT, encoding='utf-8') as f:
            old = f.read()
    rel = os.path.relpath(OUT, ROOT)
    if old == content:
        print('unity credits data: OK')
        return 0
    if check:
        print('gen_unity_credits: %s is not up to date with docs/CREDITS.md (run python3 -I unity/tools/gen_unity_credits.py)' % rel)
        return 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(content)
    print('gen_unity_credits: wrote %s' % rel)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
