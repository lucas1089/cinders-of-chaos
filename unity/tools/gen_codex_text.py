#!/usr/bin/env python3
"""Codex texts in pt-BR for the Unity client (phase 7, track Z): client/overlay/modules/client_chaos_locale/pt_br.lua -> unity/Client/Assets/Chaos/Core/CodexTextData.cs.

The main client translates the generated English Codex (codex_data.lua) by a lookup: every number of a text becomes %s and every % becomes %%, the result is the key
(game_codex/codextext.lua). pt_br.lua holds those keys in its Codex blocks. This script copies the blocks into one C# dictionary (same keys, same %s) that
Core/Phase7ZCodex.cs CodexText reads. No flag writes the file, --check compares it and exits 1 when it is old.
Run with -I: python3 -I unity/tools/gen_codex_text.py [--check]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "client", "overlay", "modules", "client_chaos_locale", "pt_br.lua")
OUT = os.path.join(ROOT, "unity", "Client", "Assets", "Chaos", "Core", "CodexTextData.cs")

# the blocks of pt_br.lua that belong to the Codex: from a start marker up to an end marker (both lines are not part of the block)
BLOCKS = [
    ("-- Codex (game_codex/codextext.lua)", "-- client/overlay/modules/game_npctradewindow/tradeview.lua"),
    ("-- Codex: more paragraphs", "-- BEGIN GENERATED UNIQUE DESCRIPTIONS"),
]

STR = r'"((?:[^"\\]|\\.)*)"'
ENTRY = re.compile(r'^\s*\[' + STR + r'\]\s*=\s*' + STR + r',?\s*$')
ESC = {"n": "\n", "t": "\t", "\\": "\\", '"': '"', "'": "'", "r": "\r"}


def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n in ESC:
                out.append(ESC[n]); i += 2; continue
            m = re.match(r"\d{1,3}", s[i + 1:])
            if m:
                out.append(chr(int(m.group(0)))); i += 1 + len(m.group(0)); continue
        out.append(c); i += 1
    return "".join(out)


def cs(s):
    out = ['"']
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        elif ch == "\r": out.append("\\r")
        elif ord(ch) < 32: out.append("\\u%04x" % ord(ch))
        else: out.append(ch)
    out.append('"')
    return "".join(out)


def collect():
    lines = open(SRC, encoding="utf-8").read().split("\n")
    entries, skipped = [], []
    for start, end in BLOCKS:
        a = next((i for i, l in enumerate(lines) if start in l), None)
        if a is None:
            raise SystemExit("start marker not found: " + start)
        b = next((i for i in range(a + 1, len(lines)) if end in lines[i]), None)
        if b is None:
            raise SystemExit("end marker not found: " + end)
        for l in lines[a + 1:b]:
            if not l.strip() or l.strip().startswith("--"):
                continue
            m = ENTRY.match(l)
            if not m:
                skipped.append(l.strip()[:80])
                continue
            entries.append((unescape(m.group(1)), unescape(m.group(2))))
    return entries, skipped


def render(entries):
    seen = {}
    for k, v in entries:
        seen[k] = v
    out = [
        "// GENERATED by unity/tools/gen_codex_text.py from client_chaos_locale/pt_br.lua (the Codex blocks); do not edit by hand.",
        "// The pt-BR Codex texts: key = the English text with every number as %s and every % as %%, value = the translation with the same %s.",
        "using System.Collections.Generic;",
        "",
        "namespace Chaos.Core",
        "{",
        "    public static class CodexTextData",
        "    {",
        "        public static readonly Dictionary<string, string> Table = new Dictionary<string, string>",
        "        {",
    ]
    for k in sorted(seen):
        out.append("            [%s] = %s," % (cs(k), cs(seen[k])))
    out += ["        };", "    }", "}", ""]
    return "\n".join(out)


def main():
    entries, skipped = collect()
    if skipped:
        print("skipped %d lines that are not plain entries (first: %s)" % (len(skipped), skipped[0]))
    text = render(entries)
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("CodexTextData.cs is old: run python3 -I unity/tools/gen_codex_text.py")
            return 1
        print("codex text: ok (%d entries)" % len(set(k for k, _ in entries)))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d entries)" % (OUT, len(set(k for k, _ in entries))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
