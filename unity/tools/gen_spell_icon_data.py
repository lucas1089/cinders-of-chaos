#!/usr/bin/env python3
"""Spell icon cells of the Unity client (O433 phase 6, track U): Core/SpellIconData.cs from the main client's spell data.

The main client draws a Chaos spell as one cell of the three spell icon sheets (client/overlay/data/images/game/spells/
spell-icons-{32x32,22x24,20x20}.png, 20 columns). game_chaosspells/spelldata.lua holds the cell of every Chaos spell
(clientId) next to its server spell id and its words. The Unity core needs the same table without a Lua reader, so this
tool writes it as C#. Stock spells have no row (their cells come from the base client's own table, which is not in git):
the Unity spellbook draws its element colour for them, as it did before.

usage: python3 -I unity/tools/gen_spell_icon_data.py [--check]
  --check: the committed file matches what the spell data gives (exit 1 when not); nothing is written.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SPELLDATA = os.path.join(REPO, 'client', 'overlay', 'modules', 'game_chaosspells', 'spelldata.lua')
OUT = os.path.join(REPO, 'unity', 'Client', 'Assets', 'Chaos', 'Core', 'SpellIconData.cs')


def rows():
    out = []
    for line in open(SPELLDATA, encoding='utf-8').read().splitlines():
        m = re.match(r'\s*\{ id = (\d+), name = "([^"]+)", words = "([^"]+)"', line)
        cid = re.search(r'clientId = (\d+)', line)
        if m and cid:
            out.append((int(m.group(1)), m.group(3), int(cid.group(1))))
    return out


def render():
    lines = [
        '// GENERATED by unity/tools/gen_spell_icon_data.py from client/overlay/modules/game_chaosspells/spelldata.lua. Do not edit.',
        '// One row per Chaos spell: the server spell id, its words and its cell (1-based, 20 columns) in the three spell icon sheets.',
        'namespace Chaos.Core',
        '{',
        '    public static partial class SpellIcons',
        '    {',
        '        static readonly object[] Data =',
        '        {',
    ]
    for sid, words, cell in rows():
        lines.append('            %d, "%s", %d,' % (sid, words, cell))
    lines += ['        };', '    }', '}', '']
    return '\n'.join(lines)


def main(argv):
    text = render()
    if '--check' in argv:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if have != text:
            print('SpellIconData.cs is out of date: run python3 -I unity/tools/gen_spell_icon_data.py')
            return 1
        print('spell icon data ok (%d spells)' % len(rows()))
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d spells)' % (os.path.relpath(OUT, REPO), len(rows())))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
