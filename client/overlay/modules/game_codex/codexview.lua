-- The Codex window's logic that needs no client API (tested by codexview_test.lua): search, filters, the item level
-- view of a modifier's tiers, shared sections, finding an entry, column widths.
--   CodexView.tokens(query)                       lower-case words of a search
--   CodexView.hasWord(text, word)                 a search word at the start of a word of the text
--   CodexView.searchText(entry, shared)           everything a search looks at (name, line, every text of the page)
--   CodexView.matches(entry, filters, values, words, shared)
--   CodexView.list(tab, query, values, shared)    the entries of a tab that pass the search and the filters
--   CodexView.tierRows(level, data)               {{tier, weight}} that roll at an item level, best first
--   CodexView.tierChances(level, data)            {[tier] = percent with one decimal}
--   CodexView.subline(entry, values, data)        the list line: the entry's own, or its tiers at the chosen level
--   CodexView.section(section, shared)            a section, or the shared one it refers to
--   CodexView.find(data, id)                      tab index, entry
--   CodexView.idForMod(key, group, data)          the Codex id of a modifier key the server sends (crafting bench)
--   CodexView.columns(w, total, gap)              pixel widths of table columns that add up to `total`
--   CodexView.highlight(section, entry, values, data)  {[row] = true}: the tier rows that roll at the chosen level
-- Data: CodexData (codex_data.lua, generated by server/tools/gen_codex_data.lua).
local function tr(s, ...) local g = rawget(_G, 'tr') if g then return g(s, ...) end if select('#', ...) > 0 then return string.format(s, ...) end return s end -- i18n (client_chaos_locale)

CodexView = {}
local V = CodexView
local floor = math.floor

function V.tokens(query)
  local out = {}
  for word in tostring(query or ''):lower():gmatch('%S+') do
    out[#out + 1] = word
  end
  return out
end

function V.section(section, shared)
  if section and section.ref then
    return shared and shared[section.ref] or nil
  end
  return section
end

local function addText(parts, v)
  if type(v) == 'string' then
    parts[#parts + 1] = v
  elseif type(v) == 'table' then
    for _, x in ipairs(v) do addText(parts, x) end
  end
end

function V.searchText(entry, shared)
  if entry._search then return entry._search end
  local parts = { entry.name or '', entry.sub or '' }
  for _, s in ipairs(entry.sections or {}) do
    s = V.section(s, shared)
    if s then
      addText(parts, s.h)
      addText(parts, s.p)
      addText(parts, s.rows)
    end
  end
  entry._search = table.concat(parts, '\n'):lower()
  return entry._search
end

local function has(list, value)
  if type(list) ~= 'table' then return list == value end
  for _, x in ipairs(list) do
    if x == value then return true end
  end
  return false
end

-- one filter: value '' (or nil) passes everything; "eq" the entry's field equals it, "has" the entry's list holds it,
-- "max" the entry's number is at most it, "ilvl" changes only what the list shows
function V.passes(entry, filter, value)
  if value == nil or value == '' or filter.match == 'ilvl' then return true end
  local field = entry.f and entry.f[filter.key]
  if filter.match == 'has' then
    return has(field, value)
  elseif filter.match == 'max' then
    local n, limit = tonumber(field), tonumber(value)
    return n ~= nil and limit ~= nil and n <= limit
  end
  return field == value
end

-- a search word matches the start of a word of the text ("kill" finds "Life on Kill", not "Skill"); a word that
-- starts with a sign or a digit ("+5", "1-3") matches anywhere
function V.hasWord(text, word)
  if word:sub(1, 1):match('%a') then
    return text:find('%f[%w]' .. word:gsub('[%^%$%(%)%%%.%[%]%*%+%-%?]', '%%%0')) ~= nil
  end
  return text:find(word, 1, true) ~= nil
end

function V.matches(entry, filters, values, words, shared)
  for _, f in ipairs(filters or {}) do
    if not V.passes(entry, f, values and values[f.key]) then return false end
  end
  if words and #words > 0 then
    local text = V.searchText(entry, shared)
    for _, w in ipairs(words) do
      if not V.hasWord(text, w) then return false end
    end
  end
  return true
end

function V.list(tab, query, values, shared)
  local words, out = V.tokens(query), {}
  for _, e in ipairs(tab and tab.entries or {}) do
    if V.matches(e, tab.filters, values, words, shared) then out[#out + 1] = e end
  end
  return out
end

-- the same rules as the server (chaos_item_mods.lua M.tierRows / M.tierChances)
function V.maxTier(level, data)
  level = tonumber(level) or 0
  local best = 1
  for t, need in ipairs(data.tierLevels) do
    if level >= need then best = t end
  end
  return best
end

function V.tierRows(level, data)
  local top, rows = V.maxTier(level, data), {}
  for t = top, math.max(1, top - data.tierWindow + 1), -1 do
    rows[#rows + 1] = { t, data.tierWeights[t] or 1 }
  end
  return rows
end

function V.tierChances(level, data)
  local rows, total, out = V.tierRows(level, data), 0, {}
  for _, r in ipairs(rows) do total = total + r[2] end
  for _, r in ipairs(rows) do out[r[1]] = floor(r[2] * 1000 / total + 0.5) / 10 end
  return out
end

-- the item level chosen in the tab's filters (the "ilvl" filter), or nil
function V.levelOf(values, filters)
  for _, f in ipairs(filters or {}) do
    if f.match == 'ilvl' then
      local v = values and tonumber(values[f.key])
      if v then return v end
    end
  end
  return nil
end

function V.subline(entry, level, data)
  if not level or not entry.tv or not data then return entry.sub or '' end
  local rows = V.tierRows(level, data)
  local hi, lo = rows[1][1], rows[#rows][1]
  local range = lo == hi and string.format('T%d %s', hi, entry.tv[hi])
    or string.format('T%d-T%d: %s to %s', lo, hi, entry.tv[lo], entry.tv[hi])
  return tr('Item level %d: %s', level, range)
end

function V.highlight(section, entry, level, data)
  local out = {}
  if not (section and section.tiers and level and data) then return out end
  for _, r in ipairs(V.tierRows(level, data)) do out[r[1]] = true end
  return out
end

function V.find(data, id)
  for i, tab in ipairs(data and data.tabs or {}) do
    for _, e in ipairs(tab.entries) do
      if e.id == id then return i, e end
    end
  end
  return nil
end

-- a modifier as the crafting bench names it (attribute key, group) -> the id of its page
function V.idForMod(key, group, data)
  key = tostring(key or ''):lower()
  if key == '' then return nil end
  local candidates
  if group == 'rift' then
    candidates = { 'rift:' .. key }
  else
    candidates = { 'mod:' .. key, 'power:' .. (key:match('^chaos_mod_(.+)$') or key) }
  end
  for _, id in ipairs(candidates) do
    if V.find(data, id) then return id end
  end
  return nil
end

-- column widths in pixels from relative widths: each at least 1, together exactly total - gaps
function V.columns(w, total, gap)
  local n = #w
  gap = gap or 0
  local free = math.max(n, total - gap * (n - 1))
  local sum = 0
  for _, x in ipairs(w) do sum = sum + math.max(0, tonumber(x) or 0) end
  local out, used = {}, 0
  for i, x in ipairs(w) do
    local share = sum > 0 and math.max(0, tonumber(x) or 0) / sum or 1 / n
    out[i] = math.max(1, floor(free * share))
    used = used + out[i]
  end
  out[n] = math.max(1, out[n] + free - used)
  return out
end

return CodexView
