-- luajit huntmath_test.lua && lua5.3 huntmath_test.lua
local dir = (arg and arg[0] or ''):match('^(.*[/\\])') or './'
dofile(dir .. 'huntmath.lua')
local fails = 0
local function eq(a, b, what)
  if a ~= b then print('FAIL ' .. what .. ': ' .. tostring(a) .. ' ~= ' .. tostring(b)); fails = fails + 1 end
end
eq(HuntMath.duration(9), '9s', 'seconds')
eq(HuntMath.duration(65), '1m 05s', 'minutes')
eq(HuntMath.duration(3725), '1h 02m 05s', 'hours')
eq(HuntMath.duration(90061), '1d 01h 01m', 'days')
eq(HuntMath.duration(-5), '0s', 'negative')
eq(HuntMath.duration(nil), '0s', 'nil')
eq(HuntMath.short(999), '999', 'short small')
eq(HuntMath.short(1234), '1.2k', 'short k')
eq(HuntMath.short(15000), '15k', 'short round k')
eq(HuntMath.short(2500000), '2.5kk', 'short kk')
eq(HuntMath.short(3200000000), '3.2kkk', 'short kkk')
eq(HuntMath.short(-45600), '-45.6k', 'short negative')
eq(HuntMath.exact(1234567), '1,234,567', 'exact')
eq(HuntMath.exact(123456), '123,456', 'exact no leading comma')
eq(HuntMath.exact(-1000), '-1,000', 'exact negative')
eq(HuntMath.exact(12), '12', 'exact small')
eq(HuntMath.elapsed(100, false, 10, 15), 105, 'clock runs')
eq(HuntMath.elapsed(100, true, 10, 15), 100, 'clock paused')
eq(HuntMath.elapsed(100, false, 10, 5), 100, 'clock skew')
eq(HuntMath.nextLevel(-1), '-', 'no rate')
eq(HuntMath.nextLevel(3725), '1h 02m 05s', 'next level')
eq(HuntMath.profitColor(5), HuntMath.GAIN_COLOR, 'profit colour')
eq(HuntMath.profitColor(-5), HuntMath.LOSS_COLOR, 'loss colour')
eq(HuntMath.profitColor(0), HuntMath.TEXT_COLOR, 'even colour')
local label, color = HuntMath.itemLabel('magic sword', 5, 0, 0)
eq(label, '[Legendary] Magic sword', 'rarity label')
eq(color, '#ffd040', 'rarity colour')
label, color = HuntMath.itemLabel('soulreaper', 0, 1, 0)
eq(label, '[Unique] Soulreaper', 'unique label')
eq(color, HuntMath.UNIQUE_COLOR, 'unique colour')
label, color = HuntMath.itemLabel('orb of chaos', 0, 0, 1)
eq(label, 'Orb of chaos', 'orb label')
eq(color, HuntMath.ORB_COLOR, 'orb colour')
eq(select(2, HuntMath.itemLabel('gold coin', 0, 0, 0)), HuntMath.TEXT_COLOR, 'plain colour')
local loot = HuntMath.lootRows({ { 3031, 120, 120, 'gold coin', 0, 0, 0 }, { 1, 2, 0, 'orb of chaos', 0, 0, 1 }, 'bad' })
eq(#loot, 2, 'loot rows (bad row skipped)')
eq(loot[1].id, 3031, 'loot id')
eq(loot[2].orb, true, 'loot orb flag')
local sup = HuntMath.supplyRows({ { 266, 8, 360, 'health potion' } })
eq(sup[1].value, 360, 'supply value')
local sp = HuntMath.specialRows({ { 2, 1, 'soulreaper', 0, 1, 0 } })
eq(sp[1].unique, true, 'special unique')
eq(sp[1].name, 'soulreaper', 'special name')
local kills = HuntMath.killRows({ { 'Dragon', 3 }, { 'Dragon Lord', 1 } }, 4)
eq(kills[1].percent, 75, 'kill share')
eq(kills[2].name, 'Dragon Lord', 'kill name')
eq(#HuntMath.killRows(nil, 0), 0, 'no kills')
local text = HuntMath.summary({ t = 3600, xp = 1000, xph = 1000, lv = 500, lvh = 500, sv = 100, pf = 400, pfh = 400, kc = 4,
  k = { { 'Dragon', 4 } } })
eq(text:find('Profit: 400 gold', 1, true) ~= nil, true, 'summary profit')
eq(text:find('4x Dragon', 1, true) ~= nil, true, 'summary kills')
if fails > 0 then os.exit(1) end
print('hunt tracker tests OK')
