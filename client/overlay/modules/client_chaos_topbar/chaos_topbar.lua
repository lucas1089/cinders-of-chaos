-- ---------------------------------------------------------------- helpers
-- Sandboxed module environments fall back to _G through __index, so use
-- rawget to avoid picking up an unrelated global called "toggle".
local function getModule(name)
  local m = modules and modules[name]
  if type(m) ~= 'table' then return nil end
  return m
end

-- Modules that load on first use (autoload: false; client/MANIFEST.md "Lazy modules"). Their menu entry stays and
-- loads the module when it is used; nothing here loads one just to draw the menu.
local LAZY_MODULES = { game_codex = true, client_chaos_credits = true }

local function loadLazy(name)
  if not LAZY_MODULES[name] then return nil end
  if g_modules and g_modules.ensureModuleLoaded then pcall(g_modules.ensureModuleLoaded, name) end
  return getModule(name)
end

local function lazyKnown(name)
  if not LAZY_MODULES[name] or not g_modules or not g_modules.getModule then return false end
  return g_modules.getModule(name) ~= nil
end

local function resolvePath(root, path)
  local cur = root
  for key in string.gmatch(path, '[^%.]+') do
    if type(cur) ~= 'table' then return nil end
    cur = rawget(cur, key)
    if cur == nil then return nil end
  end
  return cur
end

local function isAlive(widget)
  if not widget then return false end
  local ok, destroyed = pcall(function() return widget:isDestroyed() end)
  return ok and not destroyed
end

local function toggleWidget(w)
  if w:isVisible() then w:hide() else w:show(); w:raise(); w:focus() end
end

-- Finds a callable action for an entry or returns nil.
local function findAction(entry)
  if entry.unless and entry.unless() then return nil end
  if entry.custom then
    if entry.available and not entry.available() then return nil end
    return entry.custom
  end
  for _, modName in ipairs(entry.modules or {}) do
    local m = getModule(modName)
    if not m and lazyKnown(modName) then
      -- not loaded yet: the action loads it, then runs the entry again against the loaded module
      return function()
        if loadLazy(modName) then
          local action = findAction(entry)
          if action then action() end
        end
      end
    end
    if m then
      for _, path in ipairs(entry.fns or {}) do
        local fn = resolvePath(m, path)
        if type(fn) == 'function' then
          -- functions declared as Module:fn() expect the module as self; plain ones ignore it
          -- (noSelf: the function takes an optional argument of its own, so call it bare)
          if entry.noSelf then return function() fn() end end
          return function() fn(m) end
        end
      end
      for _, varName in ipairs(entry.windows or {}) do
        local w = rawget(m, varName)
        if w and type(w) ~= 'function' and isAlive(w) then
          return function() toggleWidget(w) end
        end
      end
    end
  end
  return nil
end

local function call(path, ...)
  local modName, rest = path:match('^([%w_]+)%.(.+)$')
  local fn = resolvePath(getModule(modName), rest)
  if type(fn) == 'function' then return fn(...) end
end

local function openQuestLog()
  if g_game.requestQuestLog then g_game.requestQuestLog() end
  call('game_questlog.toggle')
end

local function logout()
  local gi = getModule('game_interface')
  if gi and type(rawget(gi, 'tryLogout')) == 'function' then
    gi.tryLogout()
  elseif g_game and g_game.isOnline() then
    g_game.safeLogout()
  end
end

-- in game: log out (the stock exit button did the same); on the login screen: close the client
local function exitClient()
  if g_game and g_game.isOnline() then
    logout()
  else
    g_app.exit()
  end
end

local function openCommunity()
  if ChaosTopBar.COMMUNITY_URL ~= '' then
    g_platform.openUrl(ChaosTopBar.COMMUNITY_URL)
  else
    displayInfoBox(tr('Join Discord'), tr('The community link is not available yet.'))
  end
end

-- Admin / gamemaster check. Defaults to false. Uses whichever accessor the local player
-- exposes in this client build; a server can also call ChaosTopBar.setAdmin(true).
local function hasAdminAccess()
  if adminOverride ~= nil then return adminOverride end
  if not (g_game and g_game.isOnline and g_game.isOnline()) then return false end
  local ok, result = pcall(function()
    if g_game.isGM and g_game.isGM() then return true end
    local player = g_game.getLocalPlayer()
    if not player then return false end
    for _, name in ipairs({ 'isAdmin', 'isGamemaster', 'isGameMaster' }) do
      local f = player[name]
      if type(f) == 'function' and f(player) == true then return true end
    end
    for _, name in ipairs({ 'getGroup', 'getGroupId', 'getAccess', 'getAccessLevel' }) do
      local f = player[name]
      if type(f) == 'function' then
        local v = f(player)
        if type(v) == 'number' and v >= ADMIN_MIN_GROUP then return true end
      end
    end
    return false
  end)
  return ok and result == true
end

-- ---------------------------------------------------------------- menu layout
-- entry: text, icon (topbutton_<icon>), and either custom (function) or
--        modules (candidate module names) + fns (function paths) / windows (widget globals);
--        key (a hotkey, shown in the menu and bound while in game); sub (entries of a sub-menu, opened beside the
--        drop-down); unless (function: true hides the entry, e.g. a base window a Chaos window replaces)
-- Every player command of the server is in here: the windows of the Chaos modules, and the Info & Services window
-- (game_chaosinfo) for the commands that only print text or take a short argument.
local function info(page)
  return {
    custom = function() call('game_chaosinfo.openPage', page) end,
    available = function()
      local m = getModule('game_chaosinfo')
      local offered = m and rawget(m, 'isPageOffered')
      return m ~= nil and (type(offered) ~= 'function' or offered(page))
    end,
  }
end

local function entry(text, icon, def)
  def.text, def.icon = text, icon
  return def
end

local function has(name) return function() return getModule(name) ~= nil end end

