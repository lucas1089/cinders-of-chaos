local function isOnline()
  return g_game and g_game.isOnline() or false
end

local function availableEntries(category)
  local list = {}
  local online = isOnline()
  for _, entry in ipairs(category.entries) do
    if not online and not entry.offline then
      -- login screen: only entries that make sense without a character
    elseif entry.separator then
      if #list > 0 and not list[#list].separator then list[#list + 1] = entry end
    else
      local action = findAction(entry)
      if action then list[#list + 1] = { entry = entry, action = action } end
    end
  end
  if #list > 0 and list[#list].separator then list[#list] = nil end
  return list
end

local function closeMenu()
  if isAlive(openMenu) then openMenu:destroy() end
  openMenu = nil
end

local function showCategory(category, button)
  closeMenu()
  local list = availableEntries(category)
  if #list == 0 then return end
  local menu = g_ui.createWidget('PopupMenu')
  menu:setGameMenu(true)
  for _, item in ipairs(list) do
    if item.separator then
      menu:addSeparator()
    else
      local entry, action = item.entry, item.action
      -- leading spaces leave room for the icon drawn at the left of the option
      menu:addOption('      ' .. entry.text, function()
        local ok, err = pcall(action)
        if not ok then g_logger.error('[chaos_menu] ' .. entry.text .. ': ' .. tostring(err)) end
      end)
      local option = menu:getLastChild()
      if option and entry.icon then
        pcall(function()
          option:setIcon(ICON_DIR .. entry.icon)
          option:setIconSize({ width = 16, height = 16 })
          option:setIconOffset({ x = 4, y = 2 })
        end)
      end
    end
  end
  local pos = button:getPosition()
  menu:display({ x = pos.x, y = pos.y + button:getHeight() + 2 })
  openMenu = menu
end

local function createCategoryButton(category)
  local button = g_ui.createWidget('ChaosMenuButton', buttonsPanel)
  button:setId('chaosMenu_' .. category.id)
  button:setText(category.text)
  button:setIcon(ICON_DIR .. category.icon)
  button:setWidth(button:getTextSize().width + 38)
  button.onClick = function() showCategory(category, button) end
  categoryButtons[category.id] = button
  return button
end

-- ---------------------------------------------------------------- right panel icons
-- The stock side window (icon grid, store/battle pass, options, logout) is replaced by this menu.
local function hideSideButtons()
  local sb = getModule('game_sidebuttons')
  local w = sb and rawget(sb, 'buttonsWindow')
  if isAlive(w) then
    pcall(function() if w.close then w:close() end end)
    w:hide()
  end
end

-- ---------------------------------------------------------------- refresh
-- Shows the categories that have at least one usable entry.
function ChaosTopBar.refresh()
  if not isAlive(menuBar) then return end
  local width = 16
  for _, category in ipairs(CATEGORIES) do
    local button = categoryButtons[category.id]
    if button then
      local show = #availableEntries(category) > 0
      if show and category.admin then show = hasAdminAccess() end
      button:setVisible(show)
      if show then width = width + button:getWidth() + 4 end
    end
  end
  menuBar:setWidth(width)
  -- in game the bar sits on the game root panel; on the login screen on the root widget
  local parent = isOnline() and gameParent or g_ui.getRootWidget()
  if parent and menuBar:getParent() ~= parent then
    menuBar:setParent(parent)
    menuBar:addAnchor(AnchorTop, 'parent', AnchorTop)
    menuBar:addAnchor(AnchorHorizontalCenter, 'parent', AnchorHorizontalCenter)
  end
  menuBar:setVisible(true)
  menuBar:raise()
end

function ChaosTopBar.setAdmin(value)
  adminOverride = value and true or false
  ChaosTopBar.refresh()
end

-- Lets other modules add an entry to a category: ChaosTopBar.addEntry('chaos', {text=..., icon=..., modules=..., fns=...})
function ChaosTopBar.addEntry(categoryId, entry)
  for _, category in ipairs(CATEGORIES) do
    if category.id == categoryId and entry and entry.text then
      table.insert(category.entries, entry)
      ChaosTopBar.refresh()
      return true
    end
  end
  return false
end

-- {category id -> {entry texts}} of what the menu would show now (for checks and tools)
function ChaosTopBar.available()
  local out = {}
  for _, category in ipairs(CATEGORIES) do
    local texts = {}
    for _, item in ipairs(availableEntries(category)) do
      if not item.separator then texts[#texts + 1] = item.entry.text end
    end
    out[category.id] = texts
  end
  return out
end

-- runs the entry with this text, as a click on it would; returns false when it is not available
function ChaosTopBar.run(text)
  for _, category in ipairs(CATEGORIES) do
    for _, item in ipairs(availableEntries(category)) do
      if not item.separator and item.entry.text == text then
        item.action()
        return true
      end
    end
  end
  return false
end

local function scheduleRefresh(delay)
  if refreshEvent then removeEvent(refreshEvent) end
  refreshEvent = scheduleEvent(function()
    refreshEvent = nil
    hideSideButtons()
    ChaosTopBar.refresh()
  end, delay or 400)
end

local function onGameStart()
  hideSideButtons()
  ChaosTopBar.refresh()
  -- game modules (and game_sidebuttons re-adding its window) finish a moment after onGameStart
  scheduleRefresh(400)
  scheduleEvent(function() hideSideButtons(); ChaosTopBar.refresh() end, 3000)
end

local function onGameEnd()
  adminOverride = nil
  closeMenu()
  -- back to the login-screen entries once the game interface is gone
  scheduleEvent(function() ChaosTopBar.refresh() end, 100)
end

-- ---------------------------------------------------------------- stock top strip
-- client_topmenu shows its strip on the login screen (and again on every logout); its buttons
-- are in this menu now, so it stays hidden.
local stockTopMenu
local function hideStockTopMenu()
  local tm = getModule('client_topmenu')
  local getter = tm and rawget(tm, 'getTopMenu')
  local w = type(getter) == 'function' and getter() or nil
  if not isAlive(w) then return end
  stockTopMenu = w
  w:hide()
  w.onVisibilityChange = function(widget, visible)
    if visible then widget:hide() end
  end
end

-- ---------------------------------------------------------------- lifecycle
function init()
  g_ui.importStyle('topbar')

  local parent
  local gi = getModule('game_interface')
  if gi and type(rawget(gi, 'getRootPanel')) == 'function' then
    parent = gi.getRootPanel()
  end
  parent = parent or g_ui.getRootWidget()
  gameParent = parent

  -- anchored to the top of the game root panel (in the extended view the map panel is larger than
  -- the window, so its top edge is off screen)
  menuBar = g_ui.createWidget('ChaosMenuBar', parent)
  buttonsPanel = menuBar:getChildById('buttons')

  for _, category in ipairs(CATEGORIES) do
    createCategoryButton(category)
  end

  -- pushFront: signalcall stops at the first handler that returns a value, and some stock
  -- handlers do, so a handler at the end of the list may never run
  connect(g_game, { onGameStart = onGameStart, onGameEnd = onGameEnd }, true)
  hideStockTopMenu()
  if g_game.isOnline() then onGameStart() else ChaosTopBar.refresh() end
end

function terminate()
  disconnect(g_game, { onGameStart = onGameStart, onGameEnd = onGameEnd })
  if refreshEvent then removeEvent(refreshEvent) refreshEvent = nil end
  closeMenu()
  if isAlive(menuBar) then menuBar:destroy() end
  if isAlive(stockTopMenu) then
    stockTopMenu.onVisibilityChange = nil
    stockTopMenu:show()
  end
  menuBar, buttonsPanel, categoryButtons, gameParent, stockTopMenu = nil, nil, {}, nil, nil
  ChaosTopBar = nil
end
