local function isOnline()
  return g_game and g_game.isOnline() or false
end

-- the unlock state of an entry (topbar_unlocks.lua, O259): 'open' | 'locked' | 'hidden', and its level. Without that file,
-- or before the server's state came, every entry is open.
local function unlockStatus(text)
  if not ChaosTopBarUnlocks then return 'open' end
  local ok, status, level = pcall(ChaosTopBarUnlocks.status, text)
  if not ok then return 'open' end
  return status, level
end

local function unlockIsNew(text)
  if not ChaosTopBarUnlocks then return false end
  local ok, isNew = pcall(ChaosTopBarUnlocks.isNew, text)
  return ok and isNew == true
end

-- the player opened an entry: its "New" badge goes
local function unlockOpened(text)
  if ChaosTopBarUnlocks then pcall(ChaosTopBarUnlocks.markOpened, text) end
end

-- the usable entries of a list (a category or a sub-menu): {entry, action} items, separators, and {entry, sub} items
-- for sub-menus with at least one usable entry
local function availableEntries(entries)
  local list = {}
  local online = isOnline()
  for _, entry in ipairs(entries) do
    if not online and not entry.offline then
      -- login screen: only entries that make sense without a character
    elseif entry.separator then
      if #list > 0 and not list[#list].separator then list[#list + 1] = entry end
    elseif entry.sub then
      local inner = availableEntries(entry.sub)
      if #inner > 0 then list[#list + 1] = { entry = entry, sub = inner } end
    else
      local action = findAction(entry)
      if action then
        -- O259: an entry of a system the character has not unlocked is hidden; the next one to unlock shows grey, with its level
        local status, level = unlockStatus(entry.text)
        if status == 'open' then
          list[#list + 1] = { entry = entry, action = action }
        elseif status == 'locked' then
          list[#list + 1] = { entry = entry, locked = level }
        end
      end
    end
  end
  if #list > 0 and list[#list].separator then list[#list] = nil end
  return list
end

-- every usable entry of a category, sub-menus flattened
local function flatEntries(entries, out)
  out = out or {}
  for _, item in ipairs(availableEntries(entries)) do
    if item.sub then
      for _, inner in ipairs(item.sub) do
        if not inner.separator and not inner.locked then out[#out + 1] = inner end
      end
    elseif not item.separator and not item.locked then
      out[#out + 1] = item
    end
  end
  return out
end

local function closeMenu()
  if isAlive(openMenu) then openMenu:destroy() end
  openMenu = nil
end

local function setOptionIcon(option, icon)
  if option and icon then
    pcall(function()
      option:setIcon(ICON_DIR .. icon)
      option:setIconSize({ width = 16, height = 16 })
      option:setIconOffset({ x = 4, y = 2 })
    end)
  end
end

local function runItem(item)
  local ok, err = pcall(item.action)
  if not ok then g_logger.error('[chaos_menu] ' .. item.entry.text .. ': ' .. tostring(err)) end
  unlockOpened(item.entry.text)
end

-- the text an entry shows: translated (client_chaos_locale) when the language has it
local function shownText(item)
  local t = item.entry and item.entry.text or ''
  local ok, v = pcall(tr, t)
  return ok and type(v) == 'string' and v or t
end

-- O259: the text of a row (the badge "New" after an entry just unlocked, "Level N" after the locked one) and its look
local LOCK_IMAGE = '/images/game/depot/lock' -- the padlock of the depot art, 10 x 12
local COLOR_NEW, COLOR_LOCKED, COLOR_NORMAL = '#ffd24a', '#7a7466', '#d6c9ae' -- COLOR_NORMAL: ChaosMenuButton in topbar.otui

local function tx(text)
  local ok, v = pcall(tr, text)
  return ok and type(v) == 'string' and v or text
end

local function subHasNew(list)
  for _, it in ipairs(list or {}) do
    if it.sub then
      if subHasNew(it.sub) then return true end
    elseif it.entry and not it.separator and not it.locked and unlockIsNew(it.entry.text) then
      return true
    end
  end
  return false
end

local function rowText(item)
  local isNew = (item.sub and subHasNew(item.sub)) or (not item.sub and not item.locked and unlockIsNew(item.entry.text))
  return ChaosTopBarUnlocksLogic.rowText(shownText(item), item.locked and 'locked' or 'open', item.locked, isNew, tx)
end

local function decorateRow(option, item)
  if not option then return end
  pcall(function()
    if item.locked then
      option:setColor(COLOR_LOCKED)
      option:setIcon(LOCK_IMAGE)
      option:setIconSize({ width = 10, height = 12 })
      option:setIconOffset({ x = 7, y = 3 })
    elseif (item.sub and subHasNew(item.sub)) or (not item.sub and unlockIsNew(item.entry.text)) then
      option:setColor(COLOR_NEW)
    end
  end)
end

-- a click on a locked row says when it opens
local function lockedClick(item)
  if ChaosTopBarUnlocks then pcall(ChaosTopBarUnlocks.blockedMessage, item.entry.text) end
end

-- ---------------------------------------------------------------- sub-menus ("More")
-- A sub-menu opens beside its entry and the drop-down stays open (live test winpkg-35: "More" closed the drop-down
-- and the extra options came up as a separate popup near the player). The engine keeps one popup menu at a time
-- (UIPopupMenu:display destroys the one shown), so the sub-menu is a plain widget in the popup menu's style. The
-- drop-down holds the mouse grab: its press and release handlers pass the sub-menu's clicks on, and a press outside
-- both closes both. Opens on a click or on hovering the entry; hovering another entry closes it.
local function subItems(list, out)
  out = out or {}
  for _, item in ipairs(list) do
    if item.sub then
      subItems(item.sub, out) -- a sub-menu in a sub-menu: its entries in line
    elseif not (item.separator and (#out == 0 or out[#out].separator)) then
      out[#out + 1] = item
    end
  end
  if #out > 0 and out[#out].separator then out[#out] = nil end
  return out
end

local function closeSub(menu)
  if menu and isAlive(menu.chaosSub) then menu.chaosSub:destroy() end
  if menu then menu.chaosSub, menu.chaosSubOf = nil, nil end
end

local function openSub(menu, option, item)
  if not isAlive(menu) then return end
  if menu.chaosSubOf == option and isAlive(menu.chaosSub) then return end
  closeSub(menu)
  local sub = g_ui.createWidget('UIWidget', rootWidget)
  sub:setStyle('PopupMenu')
  local layout = UIVerticalLayout.create(sub)
  layout:setFitChildren(true)
  sub:setLayout(layout)
  sub:setFocusable(false)
  local width = menu:getWidth()
  for _, it in ipairs(subItems(item.sub)) do
    if it.separator then
      local sep = g_ui.createWidget('HorizontalSeparator', sub)
      sep:setMarginLeft(1)
      sep:setMarginRight(1)
    else
      local b = g_ui.createWidget('PopupMenuButton', sub)
      b:setText('      ' .. rowText(it))
      if not it.locked then setOptionIcon(b, it.entry.icon) end
      decorateRow(b, it)
      local w = b:getTextSize().width + b:getMarginLeft() + b:getMarginRight() + 50
      if it.entry.key then
        local label = g_ui.createWidget('PopupMenuShortcutLabel', b)
        label:setText(it.entry.key)
        w = w + label:getTextSize().width + label:getMarginLeft() + label:getMarginRight()
      end
      width = math.max(width, w)
      b.chaosRun = function()
        closeMenu()
        if it.locked then lockedClick(it) else runItem(it) end
      end
    end
  end
  sub:setWidth(width)
  -- beside the drop-down, level with the entry; on the left when the screen ends, kept on the screen
  local root = rootWidget:getSize()
  local x = menu:getX() + menu:getWidth() - 4
  if x + width > root.width then x = math.max(0, menu:getX() - width + 4) end
  sub:setPosition({ x = x, y = option:getY() - 3 })
  sub:raise()
  menu.chaosSub, menu.chaosSubOf = sub, option
  -- the height comes from the layout: keep it on the screen once it is known
  addEvent(function()
    if isAlive(sub) and sub:getY() + sub:getHeight() > root.height then
      sub:setY(math.max(0, root.height - sub:getHeight()))
    end
  end)
end

-- the drop-down's mouse handlers: the sub-menu's area belongs to the sub-menu
local function routeSubClicks(menu)
  menu.onMousePress = function(self, mousePos, mouseButton)
    if isAlive(self.chaosSub) and self.chaosSub:containsPoint(mousePos) then return true end
    return UIPopupMenu.onMousePress(self, mousePos, mouseButton)
  end
  menu.onMouseRelease = function(self, mousePos, mouseButton)
    local sub = self.chaosSub
    if isAlive(sub) and sub:containsPoint(mousePos) then
      if mouseButton == MouseLeftButton then
        local w = sub:recursiveGetChildByPos(mousePos, false)
        while w and w ~= sub and not w.chaosRun do w = w:getParent() end
        if w and w.chaosRun then w.chaosRun() end
      end
      return true
    end
    return false
  end
  connect(menu, { onDestroy = function(self) closeSub(self) end })
end

-- a drop-down at pos; sub-menu entries open their sub-menu beside it. Entries in alphabetical order of the shown text,
-- "More >" last (topbarlogic.lua ChaosTopBarLogic.sortList; owner request 2026-10-16)
local function showList(list, pos)
  closeMenu()
  if #list == 0 then return end
  list = ChaosTopBarLogic.sortList(list, shownText)
  local menu = g_ui.createWidget('PopupMenu')
  menu:setGameMenu(true)
  routeSubClicks(menu)
  for _, item in ipairs(list) do
    if item.separator then
      menu:addSeparator()
    elseif item.sub then
      -- leading spaces leave room for the icon drawn at the left of the option
      menu:addOption('      ' .. rowText(item) .. '  >', function() end)
      local option = menu:getLastChild()
      setOptionIcon(option, item.entry.icon)
      decorateRow(option, item)
      option.onClick = function(widget)
        if menu.chaosSubOf == widget and isAlive(menu.chaosSub) then
          closeSub(menu)
        else
          openSub(menu, widget, item)
        end
      end
      option.onHoverChange = function(widget, hovered)
        if hovered then openSub(menu, widget, item) end
      end
    elseif item.locked then
      menu:addOption('      ' .. rowText(item), function() lockedClick(item) end, item.entry.key)
      local option = menu:getLastChild()
      decorateRow(option, item)
      option.onHoverChange = function(widget, hovered)
        if hovered then closeSub(menu) end
      end
    else
      menu:addOption('      ' .. rowText(item), function() runItem(item) end, item.entry.key)
      local option = menu:getLastChild()
      setOptionIcon(option, item.entry.icon)
      decorateRow(option, item)
      option.onHoverChange = function(widget, hovered)
        if hovered then closeSub(menu) end
      end
    end
  end
  menu:display(pos)
  openMenu = menu
end

local function showCategory(category, button)
  local pos = button:getPosition()
  showList(availableEntries(category.entries), { x = pos.x, y = pos.y + button:getHeight() + 2 })
end

local function createCategoryButton(category)
  local button = g_ui.createWidget('ChaosMenuButton', buttonsPanel)
  button:setId('chaosMenu_' .. category.id)
  button:setText(category.text)
  button:setIcon(ICON_DIR .. category.icon)
  button:setWidth(button:getTextSize().width + 38)
  button.onClick = function() showCategory(category, button) end
  categoryButtons[category.id] = button
  return button
end

-- ---------------------------------------------------------------- right panel icons
-- The stock side window (icon grid, store/battle pass, options, logout) is replaced by this menu.
local function hideSideButtons()
  local sb = getModule('game_sidebuttons')
  local w = sb and rawget(sb, 'buttonsWindow')
  if isAlive(w) then
    pcall(function() if w.close then w:close() end end)
    w:hide()
  end
end

-- The base client opens the side window again whenever it lays out its side panels (game_interface calls
-- game_sidebuttons.move on login, on resize and when panels are added or moved), so hiding it once is not enough:
-- wrap move/online and hide the window again whenever it becomes visible.
local function keepSideButtonsHidden()
  local sb = getModule('game_sidebuttons')
  if not sb or rawget(sb, 'chaosHidePatched') then return end
  for _, name in ipairs({ 'move', 'online' }) do
    local original = rawget(sb, name)
    if type(original) == 'function' then
      sb[name] = function(...)
        local result = original(...)
        hideSideButtons()
        return result
      end
    end
  end
  local w = rawget(sb, 'buttonsWindow')
  if isAlive(w) then
    w.onVisibilityChange = function(widget, visible)
      if visible then scheduleEvent(hideSideButtons, 1) end
    end
  end
  sb.chaosHidePatched = true
end

-- ---------------------------------------------------------------- refresh
-- Shows the categories that have at least one usable entry. The client log (2026-10-27) showed this function taking 5 to
-- 14 ms per call (every entry of every category is looked up, and every module that adds an entry asked for a refresh),
-- so: the widget setters run only for what changed since the last call, the bar is raised only when something is above
-- it, and the callers that can come in bursts (ChaosTopBar.addEntry at module load) go through requestRefresh, which
-- runs one refresh for all of them.
local shown = {}              -- category id -> {visible, color} as last set on its button
local shownWidth, shownParent
local refreshQueued

function ChaosTopBar.refresh()
  if not isAlive(menuBar) then return end
  local width = 16
  for _, category in ipairs(CATEGORIES) do
    local button = categoryButtons[category.id]
    if button then
      local items = availableEntries(category.entries)
      local show = #items > 0
      if show and category.admin then show = hasAdminAccess() end
      -- O259: the category with a newly unlocked entry the player has not opened yet is gold
      local color = subHasNew(items) and COLOR_NEW or COLOR_NORMAL
      local last = shown[category.id]
      if not last or last.visible ~= show then button:setVisible(show) end
      if not last or last.color ~= color then pcall(function() button:setColor(color) end) end
      shown[category.id] = { visible = show, color = color }
      if show then width = width + button:getWidth() + 4 end
    end
  end
  if shownWidth ~= width then
    menuBar:setWidth(width)
    shownWidth = width
  end
  -- in game the bar sits on the game root panel; on the login screen on the root widget
  local parent = isOnline() and gameParent or g_ui.getRootWidget()
  local moved = parent and menuBar:getParent() ~= parent
  if moved then
    menuBar:setParent(parent)
    menuBar:addAnchor(AnchorTop, 'parent', AnchorTop)
    menuBar:addAnchor(AnchorHorizontalCenter, 'parent', AnchorHorizontalCenter)
  end
  if not menuBar:isVisible() then menuBar:setVisible(true) end
  local p = menuBar:getParent()
  local top = p and p.getLastChild and p:getLastChild() == menuBar
  if moved or not top then menuBar:raise() end
end

-- one refresh for a burst of requests (every module that adds an entry at load asks for one)
local function requestRefresh()
  if refreshQueued then return end
  refreshQueued = scheduleEvent(function()
    refreshQueued = nil
    ChaosTopBar.refresh()
  end, 50)
end

function ChaosTopBar.setAdmin(value)
  adminOverride = value and true or false
  ChaosTopBar.refresh()
end

-- Lets other modules add an entry: ChaosTopBar.addEntry('adventure', {text=..., icon=..., modules=..., fns=...});
-- with `under` = the text of a sub-menu entry ('More'), it goes into that sub-menu. A top-level entry goes before a
-- closing 'More' so that one stays last. An entry with `key` gets its hotkey at the next login.
function ChaosTopBar.addEntry(categoryId, entry, under)
  categoryId = CATEGORY_ALIAS[categoryId] or categoryId
  for _, category in ipairs(CATEGORIES) do
    if category.id == categoryId and entry and entry.text then
      local target = category.entries
      if under then
        target = nil
        for _, e in ipairs(category.entries) do
          if e.sub and e.text == under then target = e.sub end
        end
        if not target then return false end
      end
      local last = target[#target]
      if not under and last and last.sub then
        table.insert(target, #target, entry)
      else
        table.insert(target, entry)
      end
      requestRefresh()
      return true
    end
  end
  return false
end

-- {category id -> {entry texts}} of what the menu would show now, sub-menus flattened (for checks and tools)
function ChaosTopBar.available()
  local out = {}
  for _, category in ipairs(CATEGORIES) do
    local texts = {}
    for _, item in ipairs(flatEntries(category.entries)) do
      texts[#texts + 1] = item.entry.text
    end
    out[category.id] = texts
  end
  return out
end

-- runs the entry with this text, as a click on it would; returns false when it is not available
function ChaosTopBar.run(text)
  for _, category in ipairs(CATEGORIES) do
    for _, item in ipairs(flatEntries(category.entries)) do
      if item.entry.text == text then
        item.action()
        unlockOpened(text)
        return true
      end
    end
  end
  return false
end

-- opens a category's drop-down as a click on its button would (for checks and screenshots)
function ChaosTopBar.open(categoryId)
  local button = categoryButtons[CATEGORY_ALIAS[categoryId] or categoryId]
  for _, category in ipairs(CATEGORIES) do
    if button and category.id == (CATEGORY_ALIAS[categoryId] or categoryId) then
      showCategory(category, button)
      return true
    end
  end
  return false
end

-- ---------------------------------------------------------------- hotkeys
-- The entries with a `key` (the most used windows) are bound while in game; the menu shows the key beside the entry.
local boundKeys = {}
local function forEachKeyed(entries, fn)
  for _, e in ipairs(entries) do
    if e.sub then forEachKeyed(e.sub, fn) elseif e.key then fn(e) end
  end
end

local function bindHotkeys()
  for _, category in ipairs(CATEGORIES) do
    forEachKeyed(category.entries, function(e)
      if not boundKeys[e.key] then
        local handler = function()
          -- O259: the key of a system the character has not unlocked says when it opens
          if ChaosTopBarUnlocks and ChaosTopBarUnlocks.blockedMessage(e.text) then return true end
          local action = findAction(e)
          if action then runItem({ entry = e, action = action }) end
          return true
        end
        boundKeys[e.key] = handler
        g_keyboard.bindKeyDown(e.key, handler)
      end
    end)
  end
end

local function unbindHotkeys()
  for key, handler in pairs(boundKeys) do
    pcall(function() g_keyboard.unbindKeyDown(key, handler) end)
  end
  boundKeys = {}
end

local function scheduleRefresh(delay)
  if refreshEvent then removeEvent(refreshEvent) end
  refreshEvent = scheduleEvent(function()
    refreshEvent = nil
    hideSideButtons()
    ChaosTopBar.refresh()
  end, delay or 400)
end

local function onGameStart()
  bindHotkeys()
  keepSideButtonsHidden()
  hideSideButtons()
  ChaosTopBar.refresh()
  -- game modules (and game_sidebuttons re-adding its window) finish a moment after onGameStart
  scheduleRefresh(400)
  scheduleEvent(function() hideSideButtons(); ChaosTopBar.refresh() end, 3000)
end

local function onGameEnd()
  unbindHotkeys()
  adminOverride = nil
  closeMenu()
  -- back to the login-screen entries once the game interface is gone
  scheduleEvent(function() ChaosTopBar.refresh() end, 100)
end

-- ---------------------------------------------------------------- stock top strip
-- client_topmenu shows its strip on the login screen (and again on every logout); its buttons
-- are in this menu now, so it stays hidden.
local stockTopMenu
local function hideStockTopMenu()
  local tm = getModule('client_topmenu')
  local getter = tm and rawget(tm, 'getTopMenu')
  local w = type(getter) == 'function' and getter() or nil
  if not isAlive(w) then return end
  stockTopMenu = w
  w:hide()
  w.onVisibilityChange = function(widget, visible)
    if visible then widget:hide() end
  end
end

-- ---------------------------------------------------------------- lifecycle
-- the player's option "Show the whole menu" (System > Options; client_settings keeps it in g_settings like the others)
local function wholeMenuOption()
  local cs = modules.client_settings
  if cs and cs.getOption then
    local ok, value = pcall(cs.getOption, 'showWholeMenu')
    if ok then return value == true end
  end
  return false
end

function init()
  g_ui.importStyle('topbar')

  local parent
  local gi = getModule('game_interface')
  if gi and type(rawget(gi, 'getRootPanel')) == 'function' then
    parent = gi.getRootPanel()
  end
  parent = parent or g_ui.getRootWidget()
  gameParent = parent

  -- anchored to the top of the game root panel (in the extended view the map panel is larger than
  -- the window, so its top edge is off screen)
  menuBar = g_ui.createWidget('ChaosMenuBar', parent)
  buttonsPanel = menuBar:getChildById('buttons')

  for _, category in ipairs(CATEGORIES) do
    createCategoryButton(category)
  end

  -- pushFront: signalcall stops at the first handler that returns a value, and some stock
  -- handlers do, so a handler at the end of the list may never run
  connect(g_game, { onGameStart = onGameStart, onGameEnd = onGameEnd }, true)
  hideStockTopMenu()
  -- O259: the level-gated menu (topbar_unlocks.lua); the option "Show the whole menu" (System > Options, base patch 0154)
  if ChaosTopBarUnlocks then
    ChaosTopBarUnlocks.init({
      parent = function() return gameParent end,
      run = function(text) return ChaosTopBar and ChaosTopBar.run(text) end,
      refresh = function() if ChaosTopBar then ChaosTopBar.refresh() end end,
    }, wholeMenuOption())
  end
  if g_game.isOnline() then onGameStart() else ChaosTopBar.refresh() end
end

-- the option "Show the whole menu" (base patch 0154) tells the menu when it changes (its apply in dataset.lua)
function onOption(name, value)
  if name == 'showWholeMenu' and ChaosTopBarUnlocks then ChaosTopBarUnlocks.setShowAll(value == true) end
end

function terminate()
  disconnect(g_game, { onGameStart = onGameStart, onGameEnd = onGameEnd })
  if ChaosTopBarUnlocks then ChaosTopBarUnlocks.terminate() end
  unbindHotkeys()
  if refreshEvent then removeEvent(refreshEvent) refreshEvent = nil end
  if refreshQueued then removeEvent(refreshQueued) refreshQueued = nil end
  closeMenu()
  if isAlive(menuBar) then menuBar:destroy() end
  if isAlive(stockTopMenu) then
    stockTopMenu.onVisibilityChange = nil
    stockTopMenu:show()
  end
  menuBar, buttonsPanel, categoryButtons, gameParent, stockTopMenu = nil, nil, {}, nil, nil
  ChaosTopBar = nil
end
