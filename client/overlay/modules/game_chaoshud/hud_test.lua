-- luajit hud_test.lua && lua5.3 hud_test.lua
local dir = (arg and arg[0] or ''):match('^(.*[/\\])') or './'
dofile(dir .. 'hudmath.lua')
local fails = 0
local function eq(a, b, what)
  if a ~= b then print('FAIL ' .. what .. ': ' .. tostring(a) .. ' ~= ' .. tostring(b)); fails = fails + 1 end
end
eq(HudMath.fillWidth(50, 100, 166), 83, 'half')
eq(HudMath.fillWidth(100, 100, 166), 166, 'full')
eq(HudMath.fillWidth(150, 100, 166), 166, 'over max')
eq(HudMath.fillWidth(0, 100, 166), 0, 'empty')
eq(HudMath.fillWidth(1, 100000, 166), 1, 'tiny but alive')
eq(HudMath.fillWidth(10, 0, 166), 0, 'no max')
eq(HudMath.fillWidth(-5, 100, 166), 0, 'negative')
eq(HudMath.fillWidth(nil, nil, 166), 0, 'nil')
eq(HudMath.pair(5, 10), '5 / 10', 'pair plain')
eq(HudMath.percent(50, 100), 50, 'pct half')
eq(HudMath.percent(1, 100000), 1, 'pct tiny but alive')
eq(HudMath.percent(99999, 100000), 99, 'pct almost full is not 100')
eq(HudMath.percent(100, 100), 100, 'pct full')
eq(HudMath.percent(120, 100), 100, 'pct over max')
eq(HudMath.percent(0, 100), 0, 'pct empty')
eq(HudMath.percent(5, 0), 0, 'pct no max')
eq(HudMath.percent(nil, nil), 0, 'pct nil')
eq(HudMath.barText(5, 10, false), '5 / 10', 'text numbers')
eq(HudMath.barText(5, 10, true), '50%', 'text percent')
local node = HudMath.withChoice(nil, 'Ash Walker', true)
eq(HudMath.isOn(node, 'ash walker'), true, 'choice kept, case-insensitive')
eq(HudMath.isOn(node, 'Other'), false, 'other character unaffected')
node = HudMath.withChoice(node, 'Other', true)
node = HudMath.withChoice(node, 'ASH WALKER', false)
eq(HudMath.isOn(node, 'Ash Walker'), false, 'choice off')
eq(HudMath.isOn(node, 'Other'), true, 'other kept')
eq(next(HudMath.normalize({ a = 'x', [1] = true, b = false })), nil, 'normalize drops junk')
eq(HudMath.isOn(nil, 'x'), false, 'nil node')
eq(HudMath.isOn(node, nil), false, 'nil name')
if fails > 0 then os.exit(1) end
print('hud tests OK')
