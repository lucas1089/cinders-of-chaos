#!/usr/bin/env python3
"""Glyph art of the hub menu (O550): the white glyph atlases the bar badges and the cards draw, tinted by the skin.

usage: python3 -I client/tools/gen_topbar_icons.py [OUTDIR] [--sheet SHEET.png]
       python3 -I client/tools/gen_topbar_icons.py --check     (draws into a temporary folder, fails when a shipped file differs)
       default OUTDIR: client/overlay/modules/client_chaos_topbar/images
       --sheet also writes a contact sheet at 3x on a dark backdrop (not shipped)

Files:
  glyphs_bar.png   glyph atlas for the 32 px bar badges: 8 columns of 32 x 32 cells, the glyph 26 x 26 inside (about 21 px of
                   drawing, two thirds of the badge; owner 2026-11-14: the first size, 18 in 24, was small)
  glyphs_card.png  the same glyphs for the 44 px card badges and the 44 px phone bar badges: cells of 40 x 40, the glyph 34 x 34
                   (about 27 px of drawing)
  glyphs_mark.png  the same glyphs at 20 x 20 (the glyph 14 x 14): the pin mark in the corner of a pinned card
  ../topbar_glyph_index.lua  (next to the atlases when OUTDIR is given) generated table name -> cell (x, y) of both atlases (ChaosTopBarGlyphs)

The badge itself is the skin's own art (images/chaos/skin/button, nine-slice), so the frame follows the interface skin
(classic, forge, abyss). The glyph is white on alpha and the client tints it with image-color from ChaosTheme.palette
(accent2 for the normal state). To give one tint a lit look the white carries a vertical light ramp (1.0 at the top to
0.7 at the bottom, so an ember tint is brighter above), and a soft dark shadow is baked in below it (black stays black
under a tint). The shapes are our own (client/tools/topbar_glyphs.py). Deterministic: fixed supersampling, no random.
Needs Pillow and numpy; the shipped files are checked on the Pillow of the fx venv (ci.yml).
"""
import importlib.util
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.normpath(os.path.join(HERE, '..', 'overlay', 'modules', 'client_chaos_topbar'))
DEFAULT_OUT = os.path.join(MODULE, 'images')
INDEX_PATH = os.path.join(MODULE, 'topbar_glyph_index.lua')
COLS = 8
SS = 4                       # supersampling of the shadow and the ramp
# atlas name -> (cell, glyph size)
SIZES = {'bar': (32, 26), 'card': (40, 34), 'mark': (20, 14)}
RAMP_TOP, RAMP_BOTTOM = 1.0, 0.7
SHADOW_ALPHA, SHADOW_BLUR, SHADOW_DX, SHADOW_DY = 0.8, 0.6, 0.5, 1.0


def _load(name):
    # by path: python -I leaves the script's folder off sys.path
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + '.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


G = _load('topbar_glyphs')


def cell_image(name, cell, size):
    """one glyph: white with the light ramp, a baked shadow, in a cell x cell RGBA image"""
    m = G.mask(name, size * SS)
    n = cell * SS
    off = (cell - size) // 2 * SS
    full = Image.new('L', (n, n), 0)
    full.paste(m, (off, off))
    shadow = Image.new('L', (n, n), 0)
    shadow.paste(full, (int(SHADOW_DX * SS), int(SHADOW_DY * SS)))
    shadow = shadow.filter(ImageFilter.GaussianBlur(SS * SHADOW_BLUR)).point(lambda v: int(v * SHADOW_ALPHA))
    out = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    lay = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    lay.putalpha(shadow)
    out.alpha_composite(lay)
    yy = np.mgrid[0:n, 0:n][0].astype(np.float32)
    t = np.clip((yy - off) / (size * SS), 0, 1)
    lum = RAMP_TOP + (RAMP_BOTTOM - RAMP_TOP) * t
    grey = np.clip(lum * 255 + 0.5, 0, 255).astype(np.uint8)
    white = Image.merge('RGBA', (Image.fromarray(grey, 'L'),) * 3 + (full,))
    out.alpha_composite(white)
    return out.resize((cell, cell), Image.LANCZOS)


def slots(cell):
    """name -> (x, y) of its cell, in NAMES order"""
    return {name: ((i % COLS) * cell, (i // COLS) * cell) for i, name in enumerate(G.NAMES)}


def atlas(kind):
    cell, size = SIZES[kind]
    rows = -(-len(G.NAMES) // COLS)
    img = Image.new('RGBA', (COLS * cell, rows * cell), (0, 0, 0, 0))
    pos = slots(cell)
    for name in G.NAMES:
        img.paste(cell_image(name, cell, size), pos[name])
    return img


def index_text():
    lines = ['-- generated by client/tools/gen_topbar_icons.py: the cells of the three glyph atlases (images/glyphs_bar.png, glyphs_card.png, glyphs_mark.png);',
             '-- do not edit (python3 -I client/tools/gen_topbar_icons.py writes it, --check fails when it is stale).',
             'ChaosTopBarGlyphs = {']
    for kind in ('bar', 'card', 'mark'):
        cell, size = SIZES[kind]
        lines.append("  %s = { file = 'images/glyphs_%s', cell = %d, glyph = %d, slots = {" % (kind, kind, cell, size))
        pos = slots(cell)
        row = []
        for name in G.NAMES:
            row.append('%s = { %d, %d }' % (name, pos[name][0], pos[name][1]))
            if len(row) == 4:
                lines.append('    ' + ', '.join(row) + ',')
                row = []
        if row:
            lines.append('    ' + ', '.join(row) + ',')
        lines.append('  } },')
    lines += ['}', 'return ChaosTopBarGlyphs', '']
    return '\n'.join(lines)


def write(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, 'PNG')
    return img


def sheet(path):
    cell, size = SIZES['card']
    bar = atlas('card')
    big = Image.new('RGBA', (bar.width, bar.height), (40, 24, 20, 255))
    px = np.asarray(bar, np.float32) / 255.0
    arr = np.array([255, 180, 80], np.float32) / 255.0 * px[..., :3]
    arr = np.dstack([arr, px[..., 3]])
    lit = Image.fromarray((np.clip(arr, 0, 1) * 255).astype(np.uint8), 'RGBA')
    big.alpha_composite(lit)
    big.resize((big.width * 3, big.height * 3), Image.NEAREST).save(path)


def render(out):
    write(atlas('bar'), os.path.join(out, 'glyphs_bar.png'))
    write(atlas('card'), os.path.join(out, 'glyphs_card.png'))
    write(atlas('mark'), os.path.join(out, 'glyphs_mark.png'))
    return ['glyphs_bar.png', 'glyphs_card.png', 'glyphs_mark.png']


def same_pixels(a, b):
    ia, ib = Image.open(a).convert('RGBA'), Image.open(b).convert('RGBA')
    return ia.size == ib.size and ia.tobytes() == ib.tobytes()


def check():
    """Draw every file into a temporary folder and compare with the shipped ones (pixels, not bytes)."""
    import tempfile
    bad = []
    with tempfile.TemporaryDirectory() as tmp:
        for name in render(tmp):
            shipped = os.path.join(DEFAULT_OUT, name)
            if not os.path.exists(shipped):
                bad.append('%s is missing' % name)
            elif not same_pixels(os.path.join(tmp, name), shipped):
                bad.append('%s differs from the generator' % name)
    if not os.path.exists(INDEX_PATH):
        bad.append('topbar_glyph_index.lua is missing')
    else:
        with open(INDEX_PATH, encoding='utf-8') as f:
            if f.read() != index_text():
                bad.append('topbar_glyph_index.lua differs from the generator')
    for line in bad:
        print('gen_topbar_icons --check:', line)
    if bad:
        print('run: python3 -I client/tools/gen_topbar_icons.py')
        return 1
    print('topbar glyph art: up to date')
    return 0


def main(argv):
    args = argv[1:]
    if '--check' in args:
        return check()
    sheet_path = None
    if '--sheet' in args:
        i = args.index('--sheet')
        sheet_path = args[i + 1]
        del args[i:i + 2]
    out = args[0] if args else DEFAULT_OUT
    names = render(out)
    index = INDEX_PATH if not args else os.path.join(out, 'topbar_glyph_index.lua')
    with open(index, 'w', encoding='utf-8', newline='\n') as f:
        f.write(index_text())
    for n in names:
        print('wrote', os.path.join(out, n))
    print('wrote', index)
    if sheet_path:
        sheet(sheet_path)
        print('wrote', sheet_path)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
