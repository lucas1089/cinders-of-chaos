#!/usr/bin/env python3
"""Send offsets of the pair 36 effects redrawn IN PLACE (art_import/pack36_replace.csv) ->
server/data/lib/chaos_fx_send_offsets.lua.

    python3 -I client/tools/sprites/gen_fx_send_offsets.py           # write the Lua table
    python3 -I client/tools/sprites/gen_fx_send_offsets.py --check   # CI: the committed table is up to date

The engine draws an effect bigger than a tile with its bottom-right tile on the tile it is sent to. gen_pack36_fx.py
rebuilt 141 stock and Chaos effect ids with pack art at a FIXED send offset 0,0: art reaching past the bottom-right
tile was moved up and left as a whole (gen_pack36_fx.anchored). A 3x3 or 4x4 art sent at the target tile so sits one
or two tiles up and left of it (owner 2026-10-22: Banner Call's holy_spiral 405, a 5x5 judgement pillar cut to 4x4,
two tiles off). Position:sendMagicEffect (chaos_constants.lua) sends these ids at the target tile + this offset.

Offset per axis, from the in-place size w (tiles) and the same source art appended at its natural anchor (the
twin of pack36_<group>.csv with the same pack and source, its dx; the spellcraft set has no twin):
  * cut to REPLACE_MAX_TILES and the twin is bigger: the twin's dx (the kept part goes back where it was drawn)
  * else min(twin dx, (w - 1) // 2): a centred art comes back to the tile (2 -> 0, 3 -> 1, 4 -> 1), an art the
    pack did not centre is never pushed past its own anchor
  * no twin: (w - 1) // 2
Ids with a send offset in the spec already (628 reflect_bubble, sent through ChaosVfx) and ids whose offset is 0,0
are not listed. Missiles are not shifted. Deterministic; stdlib only.
"""
import argparse
import csv
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, 'art_import')
OUT = os.path.normpath(os.path.join(HERE, '..', '..', '..', 'server', 'data', 'lib', 'chaos_fx_send_offsets.lua'))
REPLACE_MAX_TILES = 4  # gen_pack36_fx.REPLACE_MAX_TILES


def read(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def axis(size, twin_size, twin_d):
    if twin_d is None:
        return (size - 1) // 2
    if size >= REPLACE_MAX_TILES and twin_size > size:
        return twin_d
    return min(twin_d, (size - 1) // 2)


def offsets(art=ART):
    src = {r['name']: (r['pack'], r['source']) for r in read(os.path.join(art, 'pack36_fx_sources.csv'))}
    twins = {}
    for path in sorted(glob.glob(os.path.join(art, 'pack36_*.csv'))):
        base = os.path.basename(path)
        if base in ('pack36_replace.csv', 'pack36_fx_sources.csv', 'pack36_missiles.csv'):
            continue
        for r in read(path):
            if r.get('kind') != 'effect' or r['name'] not in src:
                continue
            twins.setdefault(src[r['name']], []).append(r)
    out = []
    for r in read(os.path.join(art, 'pack36_replace.csv')):
        if r['kind'] != 'effect' or (int(r['dx']), int(r['dy'])) != (0, 0):
            continue
        w, h = int(r['w']), int(r['h'])
        pack, source = src[r['name']]
        cand = twins.get((pack, source))
        if not cand:  # another colour variant of the same effect
            stem = source.split('/')[0]
            cand = [t for (p, s), v in sorted(twins.items()) if p == pack and s.split('/')[0] == stem for t in v]
        # a directional or field twin: the one closest in size
        twin = min(cand, key=lambda t: (abs(int(t['w']) - w) + abs(int(t['h']) - h), t['name'])) if cand else None
        dx = axis(w, int(twin['w']), int(twin['dx'])) if twin else axis(w, 0, None)
        dy = axis(h, int(twin['h']), int(twin['dy'])) if twin else axis(h, 0, None)
        if (dx, dy) != (0, 0):
            note = r['note'].replace('\n', ' ')
            out.append((int(r['replace']), dx, dy, f"{w}x{h}, {note}" + (f"; twin {twin['name']}" if twin else '')))
    return sorted(out)


def render(rows):
    L = ['-- GENERATED by client/tools/sprites/gen_fx_send_offsets.py from art_import/pack36_replace.csv and the pair 36',
         '-- specs.  Do not edit by hand.  Effect ids redrawn in place with art bigger than a tile: the art keeps its',
         '-- bottom-right tile on the tile it is sent to, so Position:sendMagicEffect (chaos_constants.lua,',
         '-- fx_send_offset_core.lua) sends them at the target tile + {dx, dy} to centre them; an engine with',
         '-- src-patch 0070 takes this table (Game.setFxSendOffsets) and does it for every effect packet instead.',
         'ChaosFxSendOffset = {']
    for i, dx, dy, note in rows:
        L.append(f'\t[{i}] = {{{dx}, {dy}}},  -- {note}')
    L.append('}')
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='fail when the committed table differs')
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    text = render(offsets())
    if a.check:
        try:
            with open(a.out, encoding='utf-8') as f:
                old = f.read()
        except OSError:
            old = None
        if old != text:
            print(f'{a.out} is out of date: run client/tools/sprites/gen_fx_send_offsets.py', file=sys.stderr)
            return 1
        print(f'{a.out}: up to date')
        return 0
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {a.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
