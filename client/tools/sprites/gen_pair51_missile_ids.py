#!/usr/bin/env python3
"""Pair 51 missile names -> server/data/lib/chaos_pair51_missile_ids.lua (from client/tools/sprites/pair51_missiles.csv).

    python3 -I client/tools/sprites/gen_pair51_missile_ids.py           # write the Lua table
    python3 -I client/tools/sprites/gen_pair51_missile_ids.py --check   # CI: the committed table is up to date

import_pair51_missiles.py refills the 62 blank missile ids of pair 51 (147-250, none above 253) with missiles of two purchased
sprite sources. This turns the selection into names, the way chaos_pack41_fx_ids.lua does: ChaosPair51Missile.<name> = id
(plain name -> id, for spells and scripts that send a missile by id) and ChaosVfxMissile.p51_<name> = {id, dx, dy} for
VfxShoot(fromPos, toPos, "p51_<name>") (a missile of 2x2 tiles gets the offset 1, bigger ones w // 2, as the effects).
They show only with a client on the pair 51 that carries the missiles (dat md5 in client/MANIFEST.md); on an older pair
the ids are blank (nothing is drawn).  Deterministic; stdlib only.
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SRC = os.path.join(HERE, 'pair51_missiles.csv')
OUT = os.path.join(ROOT, 'server', 'data', 'lib', 'chaos_pair51_missile_ids.lua')
NAME = re.compile(r'^[a-z][a-z0-9_]*$')


def lua_text(rows):
    L = ['-- GENERATED by client/tools/sprites/gen_pair51_missile_ids.py from client/tools/sprites/pair51_missiles.csv: the %d missiles'
         % len(rows),
         '-- of client pair 51 refilled from two purchased sprite sources (ids %s..%s, the blank slots of the retired missiles).'
         % (min(int(r['missile_id']) for r in rows), max(int(r['missile_id']) for r in rows)),
         '-- Do not edit by hand.  ChaosPair51Missile.<name> = id; the same missiles are merged into ChaosVfxMissile as',
         '-- p51_<name> = {id, dx, dy}, so VfxShoot(fromPos, toPos, "p51_<name>") sends one.  They show only with a client on a',
         '-- pair 51 that carries them (an older client draws nothing for these ids).',
         'if not ChaosVfxMissile then',
         '\tpcall(dofile, "data/lib/chaos_vfx.lua")',
         'end',
         'ChaosVfxMissile = ChaosVfxMissile or {}',
         'ChaosPair51Missile = {}']
    for r in rows:
        L.append('ChaosPair51Missile.%s = %s  -- %s, source %s %s, %s phase(s)' % (
            r['name'], r['missile_id'], r['element'], r['source'], r['src_id'], r['phases']))
    for r in rows:
        w, h = (int(x) for x in r['size'].split('x'))
        L.append('ChaosVfxMissile.p51_%s = {id = %s, dx = %d, dy = %d}' % (r['name'], r['missile_id'], w // 2, h // 2))
    return '\n'.join(L) + '\n'


def read_rows(path=SRC):
    with open(path, newline='', encoding='utf-8') as fh:
        rows = list(csv.DictReader(fh))
    assert rows, 'missile table empty'
    assert len({r['name'] for r in rows}) == len(rows), 'missile names are not unique'
    assert all(NAME.match(r['name']) for r in rows), 'missile names must be lower case snake_case'
    ids = [int(r['missile_id']) for r in rows]
    assert len(set(ids)) == len(ids) and 1 <= min(ids) and max(ids) <= 253, 'missile ids: unique, 1..253 (254 is the weapon type)'
    return rows


def main(argv):
    text = lua_text(read_rows())
    if '--check' in argv:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
        print(OUT + (': up to date' if have == text else ': OUT OF DATE (run gen_pair51_missile_ids.py)'))
        return 0 if have == text else 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
