#!/usr/bin/env python3
"""Where each outfit's feet are, for the character select's big preview (client/MANIFEST.md "Character select").

usage: python3 -I client/tools/sprites/gen_outfit_anchors.py Tibia.dat Tibia.spr [--out PATH] [--check]

The character select draws a character 3 or 4 times its size and stands it on a pedestal. Where the feet are inside
an outfit's sprite differs from look to look (a 1x1 stock outfit, a 2x2 class look drawn in the middle of its frame,
a look with its own displacement), so a fixed offset left some looks floating above or beside the pedestal. This
tool reads the pair and writes, per creature thing (outfits, wings and auras share that category), the visible
pixels of its first south-facing frame (base layer with every addon pattern, phase 0) in the coordinates the client draws it in:
pixels relative to the top left of the creature's own tile, displacement applied (the client draws a thing's bottom
right 32x32 cell on its tile, the other cells up and left, all moved up and left by the displacement).

  [id] = {fx, fy, top, left, right, w, h}
    fx, fy        the feet: the median column of the lowest quarter of the figure, and the lowest visible row
    top, left, right  the visible bounds (wings and auras: to keep the whole picture inside the screen)
    w, h          the thing's size in tiles (the client centres a big aura by (w-1)*16, (h-1)*16)

Output (default): client/overlay/modules/client_chaos_charselect/outfit_anchors.lua, a Lua table the module loads
(`CharSelectAnchors`; charselect_core.lua does the placement). Things with no visible pixel are left out; the module
falls back to the size and displacement for them (and for looks of a newer pair). Deterministic: the same pair
writes the same file; --check exits 1 when the file differs from what the pair gives. Regenerate it with every new
pair (the dat md5 is written in the file).
"""
import argparse
import hashlib
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from datspr import Dat, Spr, sprite_index  # noqa: E402

REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(REPO, 'client', 'overlay', 'modules', 'client_chaos_charselect', 'outfit_anchors.lua')
ALPHA = 64          # a pixel counts as visible from this alpha on


def south_mask(t, spr):
    """visible pixels of the first south frame with every addon (pattern y): characters wear their class looks with
    both addons, and an addon (a cape, a staff) can reach below or beside the body"""
    x = 2 if t.px >= 4 else 0
    W, H = t.w * 32, t.h * 32
    mask = np.zeros((H, W), bool)
    for yy in range(max(1, t.py)):
        for hh in range(t.h):
            for ww in range(t.w):
                a = spr.sprite(t.sprites[sprite_index(t, x, yy, 0, 0, 0, ww, hh)])
                if a is not None:
                    oy, ox = (t.h - 1 - hh) * 32, (t.w - 1 - ww) * 32
                    mask[oy:oy + 32, ox:ox + 32] |= a[..., 3] >= ALPHA
    return mask


def anchor_of(t, spr):
    """(fx, fy, top, left, right) in tile pixels, or None for an invisible thing"""
    mask = south_mask(t, spr)
    if not mask.any():
        return None
    ys, xs = np.nonzero(mask)
    W, H = t.w * 32, t.h * 32
    dx, dy = t.flags.get('displacement', (0, 0)) if isinstance(t.flags.get('displacement'), tuple) else (0, 0)
    ox, oy = -(W - 32) - dx, -(H - 32) - dy           # canvas pixel + o = tile pixel
    bottom, top = int(ys.max()), int(ys.min())
    # the feet: the median column of the lowest quarter of the figure (a weapon or a cape reaching out to one side
    # moves it little; the lower half drifts towards a held weapon) and the lowest visible row
    lower = xs[ys >= bottom - (bottom - top + 1) * 0.25]
    fx = float(np.median(lower)) + 0.5
    return (int(np.floor(fx + ox + 0.5)), bottom + 1 + oy, top + oy, int(xs.min()) + ox, int(xs.max()) + 1 + ox)


def build(dat_path, spr_path):
    dat = Dat(dat_path)
    spr = Spr(spr_path)
    md5 = hashlib.md5(open(dat_path, 'rb').read()).hexdigest()
    rows = []
    for i, t in enumerate(dat.outfits, 1):
        if not t.sprites:
            continue
        a = anchor_of(t, spr)
        if a is None:
            continue
        rows.append('[%d]={%d,%d,%d,%d,%d,%d,%d}' % ((i,) + a + (t.w, t.h)))
    lines = ['-- Generated by client/tools/sprites/gen_outfit_anchors.py from the pair with dat md5 %s.' % md5,
             '-- Do not edit: regenerate with the tool for every new pair. Per creature thing (outfits, wings, auras):',
             '-- [id] = {feet x, feet y, top, left, right, width, height}: pixels at 1x relative to the top left of the',
             "-- creature's own tile, displacement applied (first south frame); width and height in tiles.",
             'CharSelectAnchors = {', '  dat = "%s",' % md5]
    for k in range(0, len(rows), 6):
        lines.append('  ' + ','.join(rows[k:k + 6]) + ',')
    lines.append('}')
    lines.append('return CharSelectAnchors')
    return '\n'.join(lines) + '\n', len(rows)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('dat')
    ap.add_argument('spr')
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text, n = build(a.dat, a.spr)
    if a.check:
        have = open(a.out, encoding='utf-8').read() if os.path.exists(a.out) else ''
        if have != text:
            print('%s is not what the pair gives: run %s' % (a.out, os.path.basename(__file__)))
            return 1
        print('outfit anchors up to date (%d things)' % n)
        return 0
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d things)' % (os.path.relpath(a.out, REPO), n))
    return 0


if __name__ == '__main__':
    sys.exit(main())
