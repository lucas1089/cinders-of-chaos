#!/usr/bin/env python3
"""Pair 50 effect names -> server/data/lib/chaos_pair50_fx_ids.lua (from server/data/items/pair50_effects.csv).

    python3 -I client/tools/sprites/gen_pair50_fx_ids.py           # write the Lua table
    python3 -I client/tools/sprites/gen_pair50_fx_ids.py --check   # CI: the committed table is up to date

import_pair50.py appends 600 effects after the effect 4101 of pair 49 (ids 4102..4701) and writes their table
(id, key, size, phases, ms, light, send offset). This turns it into ChaosVfx entries, the way chaos_pack36_fx_ids.lua
does: Vfx(pos, "p50_<name>_<id>") sends one at the tile it was meant for (an effect bigger than a tile is drawn with its
bottom-right tile on the tile it is sent to, so it goes to the target + (dx, dy)). Nothing in the game sends them yet; a
spell or an event script can `dofile("data/lib/chaos_pair50_fx_ids.lua")` and name one. Deterministic; stdlib only.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
SRC = os.path.join(ROOT, 'server', 'data', 'items', 'pair50_effects.csv')
OUT = os.path.join(ROOT, 'server', 'data', 'lib', 'chaos_pair50_fx_ids.lua')


def lua_text(rows):
    L = ['-- GENERATED by client/tools/sprites/gen_pair50_fx_ids.py from server/data/items/pair50_effects.csv: the effects of client',
         '-- pair 50 (ids %s..%s, two purchased sprite sources), appended after the effect 4101 of pair 49.  Do not edit by hand.'
         % (rows[0]['effect_id'], rows[-1]['effect_id']),
         '-- Merged into ChaosVfx, so Vfx(pos, name) sends one at its offset tile (an effect bigger than a tile is drawn with its',
         '-- bottom-right tile on the tile it is sent to).  They show only with a client on pair 50 or newer.',
         'if not ChaosVfx then',
         '\tpcall(dofile, "data/lib/chaos_vfx.lua")',
         'end',
         'ChaosVfx = ChaosVfx or {}']
    for r in rows:
        L.append('ChaosVfx.%s = {id = %s, dx = %s, dy = %s, ms = %s}  -- %s, %s, %s phases' % (
            r['key'], r['effect_id'], r['dx'], r['dy'], r['ms'], r['name'], r['size'], r['phases']))
    return '\n'.join(L) + '\n'


def main(argv):
    with open(SRC, newline='', encoding='utf-8') as fh:
        rows = list(csv.DictReader(fh))
    assert rows and len({r['key'] for r in rows}) == len(rows), 'effects table empty or keys not unique'
    ids = [int(r['effect_id']) for r in rows]
    assert ids == list(range(ids[0], ids[0] + len(ids))), 'effect ids are not consecutive'
    text = lua_text(rows)
    if '--check' in argv:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
        print(OUT + (': up to date' if have == text else ': OUT OF DATE (run gen_pair50_fx_ids.py)'))
        return 0 if have == text else 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote', OUT, '(%d effects)' % len(rows))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
