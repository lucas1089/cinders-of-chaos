#!/usr/bin/env python3
"""Append magic effects and missiles drawn as frame strips (art_import/fx_art.csv + PNGs) to COPIES of our 10.98 pair.

python3 -I import_fx_art.py --ours-dat Tibia.dat --ours-spr Tibia.spr --out-dir OUT \
        [--spec art_import/fx_art.csv] [--expect-first-effect N] [--expect-first-missile N] \
        [--lua-out ../../../server/data/lib/chaos_vfx_art.lua] [--catalog-out ../../../server/data/spells/vfx_art_catalog.csv]
        [--merge]

The spec (one row per thing, in id order within its kind): kind (effect | missile), name, file (PNG under art_import/),
w, h (tiles), phases, ms (per frame), dx, dy (send offset: the bottom-right tile of the art is the target tile +
(dx, dy), as in import_vfx.py / chaos_vfx.lua), note.
  effect:  the PNG is the frames left to right, each w*32 x h*32; it plays once.
  alpha (optional column): `soft` keeps the art's alpha levels 1..254 (the pair's spr has an alpha channel and the
           client blends it; art_import/big_fx.csv); otherwise alpha is cut to 0 / 255 at 128 (pixel art).
  missile: 3 x 3 direction patterns (the client's missile layout: x west/centre/east, y north/centre/south), each a
           block of `phases` frames left to right: frame f of pattern (x, y) is at ((x * phases + f) * w*32, y * h*32);
           it loops while flying.
The art is our own (client/tools/sprites/gen_fistfx_art.py builds the bone effects from PixelLab paintings).

New ids = the input's effect / missile counts + 1.. in spec order; --expect-first-* stop the run on another pair.
Outputs in --out-dir: Tibia.dat, Tibia.spr, chaos_vfx_art.lua, vfx_art_catalog.csv. --lua-out writes the Lua names:
entries merged into ChaosVfx / ChaosVfxMissile (chaos_vfx.lua), so Vfx(pos, name) / VfxShoot(from, to, name) and the
spells' ChaosSpell.vfx / vfxOr / vshoot send them at their offset. Inputs are never modified; deterministic.
--merge (for a second spec run on top of the first one's output, e.g. art_import/necro_fx.csv after fx_art.csv): the
--lua-out / --catalog-out files keep their other entries; this spec's entries replace the ones of the same names or
are appended (a re-run gives the same files). It stops if another entry already uses one of the new ids.
Verification (always): the output dat re-parses; every frame / pattern of every new thing is rendered back from the
output spr and compared pixel-exact with the art; every old dat entry is byte-identical; 3000 sampled old sprites
(plus the first and last) are unchanged.
"""
import argparse, csv, os, random, struct, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from PIL import Image
from datspr import Dat, Spr, sprite_index
from gen_effects import encode_sprite
from import_vfx import entry_bytes, render_back, tiles_of, T_

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, 'art_import')
SPEC_NAME = 'fx_art.csv'        # named in the generated Lua header (main() sets it from --spec)


def read_spec(path):
    with open(path, newline='') as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        assert r['kind'] in ('effect', 'missile'), r
        for k in ('w', 'h', 'phases', 'ms', 'dx', 'dy'):
            r[k] = int(r[k])
        assert 0 <= r['dx'] < r['w'] and 0 <= r['dy'] < r['h'], r['name']
    keys = [(r['kind'], r['name']) for r in rows]
    assert len(set(keys)) == len(keys), 'duplicate name in spec'
    return rows


def build(r):
    """-> the dict import_vfx.entry_bytes takes: frames {(phase, x, y, layer): canvas}"""
    a = np.asarray(Image.open(os.path.join(ART, r['file'])).convert('RGBA')).copy()
    if r.get('alpha') == 'soft':                             # soft art (gen_big_fx.py): every alpha level is kept
        a[a[:, :, 3] == 0] = 0
    else:                                                    # pixel art: hard edges, alpha 0 / 255
        a[a[:, :, 3] < 128] = 0
        a[:, :, 3] = np.where(a[:, :, 3] > 0, 255, 0)
    W, H, n = r['w'] * 32, r['h'] * 32, r['phases']
    frames = {}
    if r['kind'] == 'effect':
        assert a.shape[:2] == (H, W * n), (r['name'], a.shape)
        for f in range(n):
            frames[(f, 0, 0, 0)] = np.ascontiguousarray(a[:, f * W:(f + 1) * W])
        px = py = 1
    else:
        assert a.shape[:2] == (3 * H, 3 * W * n), (r['name'], a.shape)
        for y in range(3):
            for x in range(3):
                for f in range(n):
                    x0 = (x * n + f) * W
                    frames[(f, x, y, 0)] = np.ascontiguousarray(a[y * H:(y + 1) * H, x0:x0 + W])
        px = py = 3
    for k, c in frames.items():
        assert c[:, :, 3].any() or k[0] == n - 1, (r['name'], 'empty frame', k)
    return dict(kind=r['kind'], w=r['w'], h=r['h'], layers=1, px=px, py=py, phases=n, ms=r['ms'], frames=frames,
                dx=r['dx'], dy=r['dy'], disp=None)


def lua_text(rows, gens, ids):
    L = [f'-- GENERATED by client/tools/sprites/import_fx_art.py from art_import/{SPEC_NAME}: effects and missiles of our own',
         '-- art appended to the client pair after the ids of chaos_vfx.lua.  Do not edit by hand.',
         '-- Merged into ChaosVfx / ChaosVfxMissile, so Vfx(pos, name) / VfxShoot(fromPos, toPos, name) (and the spells\'',
         '-- ChaosSpell.vfx / vfxOr / vshoot) send them at their offset tile.',
         'if not ChaosVfx then',
         "\tpcall(dofile, 'data/lib/chaos_vfx.lua')",
         'end',
         'ChaosVfx = ChaosVfx or {}',
         'ChaosVfxMissile = ChaosVfxMissile or {}']
    for r, g in zip(rows, gens):
        if r['kind'] == 'effect':
            L.append(f"ChaosVfx.{r['name']} = {{id = {ids[(r['kind'], r['name'])]}, dx = {g['dx']}, dy = {g['dy']}, "
                     f"ms = {g['ms'] * g['phases']}}}  -- {r['note']}")
    for r, g in zip(rows, gens):
        if r['kind'] == 'missile':
            L.append(f"ChaosVfxMissile.{r['name']} = {{id = {ids[(r['kind'], r['name'])]}, dx = {g['dx']}, dy = {g['dy']}}}"
                     f"  -- {r['note']}")
    return '\n'.join(L) + '\n'


def write_catalog(rows, gens, ids, path):
    with open(path, 'w', newline='') as fh:
        w = csv.writer(fh, lineterminator='\n')
        w.writerow(['kind', 'id', 'name', 'size', 'send_offset', 'patterns', 'frames', 'ms', 'note'])
        for r, g in zip(rows, gens):
            w.writerow([r['kind'], ids[(r['kind'], r['name'])], r['name'], f"{g['w']}x{g['h']}", f"{g['dx']},{g['dy']}",
                        f"{g['px']}x{g['py']}", g['phases'], g['ms'], r['note']])


def merge_lua(path, rows, gens, ids):
    """keep the other entries of an existing chaos_vfx_art.lua, (re)write this spec's ones at the end"""
    ours = lua_text(rows, gens, ids).splitlines()
    ours = [l for l in ours if l.startswith('ChaosVfx.') or l.startswith('ChaosVfxMissile.')]
    names = {l.split(' = ')[0] for l in ours}
    old = open(path).read().splitlines() if os.path.exists(path) else lua_text([], [], {}).splitlines()
    keep = [l for l in old if l.split(' = ')[0] not in names]
    taken = {}
    for l in keep:
        if l.startswith('ChaosVfx') and ' = {id = ' in l:
            taken[(l.startswith('ChaosVfxMissile.'), int(l.split('{id = ')[1].split(',')[0]))] = l.split(' = ')[0]
    for l in ours:
        k = (l.startswith('ChaosVfxMissile.'), int(l.split('{id = ')[1].split(',')[0]))
        assert k not in taken, f'id {k[1]} of {l.split(" = ")[0]} is already {taken[k]} in {path}'
    return '\n'.join(keep + ours) + '\n'


def merge_catalog(path, rows, gens, ids):
    tmp = path + '.new'
    write_catalog(rows, gens, ids, tmp)
    with open(tmp, newline='') as fh:
        new = list(csv.reader(fh))
    os.remove(tmp)
    old = []
    if os.path.exists(path):
        with open(path, newline='') as fh:
            old = list(csv.reader(fh))[1:]
    keys = {(r[0], r[2]) for r in new[1:]}
    rows_ = [r for r in old if (r[0], r[2]) not in keys]
    for r in new[1:]:
        assert not any(o[0] == r[0] and o[1] == r[1] for o in rows_), f'id {r[1]} of {r[2]} is already used in {path}'
    with open(path, 'w', newline='') as fh:
        w = csv.writer(fh, lineterminator='\n')
        w.writerows([new[0]] + rows_ + new[1:])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--ours-dat', required=True); ap.add_argument('--ours-spr', required=True)
    ap.add_argument('--out-dir', required=True)
    ap.add_argument('--spec', default=os.path.join(ART, 'fx_art.csv'))
    ap.add_argument('--expect-first-effect', type=int, default=None)
    ap.add_argument('--expect-first-missile', type=int, default=None)
    ap.add_argument('--lua-out', default=None); ap.add_argument('--catalog-out', default=None)
    ap.add_argument('--merge', action='store_true',
                    help='keep the other entries of --lua-out / --catalog-out (a second spec on top of the first)')
    a = ap.parse_args()
    t0 = time.time()
    os.makedirs(a.out_dir, exist_ok=True)
    for p in (a.ours_dat, a.ours_spr):
        assert os.path.abspath(os.path.dirname(p)) != os.path.abspath(a.out_dir), 'out-dir must differ from the input dir'
    rows = read_spec(a.spec)
    global SPEC_NAME
    SPEC_NAME = os.path.basename(a.spec)
    od = Dat(a.ours_dat); ospr = Spr(a.ours_spr)
    assert od.variant[0] == 'new' and all(od.variant[1:]), f'expected our 10.98 dat (animator, u32, frame groups): {od.variant}'
    assert ospr.u32count and ospr.alpha, 'expected an alpha spr with u32 count'
    ne0, nm0 = len(od.effects), len(od.missiles)
    print(f'input: items {od.counts[0]}, outfits {od.counts[1]}, effects {ne0}, missiles {nm0}, sprites {ospr.count}')
    for flag, have in ((a.expect_first_effect, ne0), (a.expect_first_missile, nm0)):
        if flag is not None and have + 1 != flag:
            sys.exit(f'first new id would be {have + 1}, expected {flag}: wrong input pair (or already imported). '
                     f'input has effects {ne0}, missiles {nm0}')
    gens = [build(r) for r in rows]
    ids, cnt = {}, {'effect': ne0, 'missile': nm0}
    for r in rows:
        cnt[r['kind']] += 1; ids[(r['kind'], r['name'])] = cnt[r['kind']]
    assert cnt['missile'] <= 255, 'distance effects are uint8 on the wire'

    # sprite records (deduplicated inside the new set)
    recs, sid_lists = {}, []
    for g in gens:
        T = T_(g)
        lst = [0] * (g['w'] * g['h'] * g['layers'] * g['px'] * g['py'] * g['phases'])
        for (ph, x, y, l), img in g['frames'].items():
            for (ww, hh), tile in tiles_of(img, g['w'], g['h']).items():
                rec = encode_sprite(np.ascontiguousarray(tile))
                if rec is not None:
                    recs.setdefault(rec, len(recs) + 1)
                    lst[sprite_index(T, x, y, 0, l, ph, ww, hh)] = rec
        sid_lists.append(lst)
    base = ospr.count
    newrecs = list(recs)
    rid = {rec: base + i + 1 for i, rec in enumerate(newrecs)}
    entries = [entry_bytes(g, [rid[x] if x else 0 for x in lst]) for g, lst in zip(gens, sid_lists)]

    # dat: items | outfits | effects | missiles, the new entries at the end of their section
    d = od.data
    e_end = od.effects[-1].raw[1]; m_end = od.missiles[-1].raw[1]
    assert od.missiles[0].raw[0] == e_end and m_end == len(d)
    part = {k: b''.join(e for r, e in zip(rows, entries) if r['kind'] == k) for k in ('effect', 'missile')}
    out = bytearray(d[:e_end]) + part['effect'] + d[e_end:m_end] + part['missile']
    struct.pack_into('<HH', out, 8, cnt['effect'], cnt['missile'])
    open(os.path.join(a.out_dir, 'Tibia.dat'), 'wb').write(out)

    # spr (streamed: bigger table, old records shifted by 4*n, new records appended)
    m = ospr.m; oc = ospr.count; nn = len(newrecs)
    toffs = ospr.offs.astype('<u8').copy(); toffs[toffs > 0] += 4 * nn
    cur = len(m) + 4 * nn
    new_offs = []
    for rec in newrecs:
        new_offs.append(cur); cur += len(rec)
    assert cur < 1 << 32, 'spr would exceed 4 GB'
    table = np.concatenate([toffs, np.array(new_offs, dtype='<u8')]).astype('<u4')
    with open(os.path.join(a.out_dir, 'Tibia.spr'), 'wb') as f:
        f.write(struct.pack('<II', ospr.signature, oc + nn)); f.write(table.tobytes())
        pos = 8 + 4 * oc
        while pos < len(m):
            f.write(m[pos:pos + (1 << 24)]); pos += 1 << 24
        for rec in newrecs:
            f.write(rec)
    print(f"dat: effects {ne0} -> {cnt['effect']}, missiles {nm0} -> {cnt['missile']}; spr: {nn} sprites appended "
          f"({oc} -> {oc + nn})")

    lua = lua_text(rows, gens, ids)
    open(os.path.join(a.out_dir, 'chaos_vfx_art.lua'), 'w').write(lua)
    write_catalog(rows, gens, ids, os.path.join(a.out_dir, 'vfx_art_catalog.csv'))
    if a.lua_out:
        text = merge_lua(a.lua_out, rows, gens, ids) if a.merge else lua
        open(a.lua_out, 'w').write(text); print('wrote', a.lua_out, '(merged)' if a.merge else '')
    if a.catalog_out:
        if a.merge:
            merge_catalog(a.catalog_out, rows, gens, ids)
        else:
            write_catalog(rows, gens, ids, a.catalog_out)
        print('wrote', a.catalog_out, '(merged)' if a.merge else '')

    # verification
    md = Dat(os.path.join(a.out_dir, 'Tibia.dat')); ms = Spr(os.path.join(a.out_dir, 'Tibia.spr'))
    assert md.variant == od.variant, md.variant
    assert md.counts == (od.counts[0], od.counts[1], cnt['effect'], cnt['missile']), md.counts
    assert ms.count == oc + nn and md.max_sprite <= ms.count and ms.alpha and ms.signature == ospr.signature
    o_end = od.outfits[-1].raw[1]
    assert md.data[:8] == d[:8] and md.data[12:o_end] == d[12:o_end], 'items / outfits changed'
    for cat, lo, lm in (('e', od.effects, md.effects), ('m', od.missiles, md.missiles)):
        for to in lo:
            tm = lm[to.id - 1]
            assert md.data[tm.raw[0]:tm.raw[1]] == d[to.raw[0]:to.raw[1]], (cat, to.id)
    nframes = 0
    for r, g in zip(rows, gens):
        t = (md.effects if r['kind'] == 'effect' else md.missiles)[ids[(r['kind'], r['name'])] - 1]
        assert (t.w, t.h, t.layers, t.px, t.py, t.pz, t.phases) == (g['w'], g['h'], 1, g['px'], g['py'], 1, g['phases']), r['name']
        assert t.flags == {}, (r['name'], t.flags)
        back = render_back(t, ms, 1)
        assert back.keys() == g['frames'].keys(), r['name']
        for k, img in g['frames'].items():
            nframes += 1
            if not np.array_equal(back[k], img):
                raise SystemExit(f"MISMATCH {r['kind']} {r['name']} frame {k}")
    random.seed(1)
    for sid in random.sample(range(1, oc + 1), min(3000, oc)) + [1, oc]:
        x, y = ospr.sprite(sid), ms.sprite(sid)
        assert (x is None) == (y is None) and (x is None or (x == y).all()), sid
    print(f'verified: output dat parses ({md.variant}); {len(rows)} new things, {nframes} frames/patterns pixel-identical '
          f'to the art; every item, outfit, effect and missile of the input byte-identical; 3000 sampled old sprites '
          f'unchanged; {ms.count} sprites')
    print(f"ids: effects {ne0 + 1}..{cnt['effect']}, missiles {nm0 + 1}..{cnt['missile']}; done in {time.time() - t0:.1f}s")


if __name__ == '__main__':
    main()
