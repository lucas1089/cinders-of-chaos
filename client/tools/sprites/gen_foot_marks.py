#!/usr/bin/env python3
"""Where each look's feet stand, per direction, for the footprints of game_cosmeticfx (client/MANIFEST.md, O499).

usage: python3 -I client/tools/sprites/gen_foot_marks.py Tibia.dat Tibia.spr [--out PATH] [--check]

A footprint lies under the walker's feet. The engine draws a look up and left of its tile by the look's displacement,
and our class looks lean up and left with their height, so a mark on the tile centre is 3 to 12 sprite pixels from
the feet and the trail reads as walking beside the character (owner report 2026-11-11, "the footstep effect does
not follow the steps"). This tool measures the feet of every creature thing of the pair, once per direction.

The rule is the one of the character select and the look preview (gen_outfit_anchors.py `measure`, centre "feet"; the
south entry here is the same number as that table's [cx, ground]): the first frame of the direction (pattern x 0 north,
1 east, 2 south, 3 west), phase 0, base layer, every addon pattern (a character wears its class look with both
addons); the feet are the alpha-weighted centroid of the lowest 12% of the body's solid mass (thin lines, a cape tip,
a weapon, are left out; a foot that leans right of the body's columns counts). The point is in the coordinates the
client draws a creature in: pixels at 1x from the top left of the creature's OWN tile, the displacement applied.
(The measure of all directions differs from the south one by a median of 3 px across the 2628 looks, 90% within
10 px: one table row per direction, not one for all.)

  [look] = {nx, ny, ex, ey, sx, sy, wx, wy}     feet x, y for a creature facing north, east, south, west

Looks with a single direction (px 1) repeat their one frame; looks with no visible pixel are left out (the module
falls back to FALLBACK feet). A mounted player stands on its mount: the module reads the mount's row.

Output (default): client/overlay/modules/game_cosmeticfx/foot_marks.lua (`CosmeticFootMarks`). Deterministic: the same
pair writes the same file; --check exits 1 when the file differs from what the pair gives (CI job live-pair). Regenerate
it with every new pair (the dat md5 is written in the file).
"""
import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from datspr import Dat, Spr  # noqa: E402
from gen_info_lift import direction_alpha, displacement  # noqa: E402
from gen_outfit_anchors import measure  # noqa: E402

REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(REPO, 'client', 'overlay', 'modules', 'game_cosmeticfx', 'foot_marks.lua')
DIRS = 'nesw'   # pattern x 0..3


def feet_of(t, spr, x):
    """(x, y) of the feet of direction x (pattern x) in tile pixels at 1x, or None when nothing is visible"""
    dx, dy = displacement(t)
    W, H = t.w * 32, t.h * 32
    m = measure(direction_alpha(t, spr, x), -(W - 32) - dx, -(H - 32) - dy, False, 'feet')
    return None if m is None else (m[0], m[1])


def thing_feet(t, spr):
    """the 8 numbers of a creature thing (north, east, south, west), or None"""
    pts = []
    for x in range(4):
        p = feet_of(t, spr, x if t.px >= 4 else 0)
        if p is None:
            return None
        pts.append(p)
    return [v for p in pts for v in p]


def lua_text(rows, md5):
    lines = ['-- Generated by client/tools/sprites/gen_foot_marks.py from the pair with dat md5 %s.' % md5,
             '-- Do not edit: regenerate with the tool for every new pair. Per creature thing (outfits, mounts):',
             '-- [id] = {nx, ny, ex, ey, sx, sy, wx, wy}: where the feet stand for a creature facing north, east, south,',
             "-- west: pixels at 1x from the top left of the creature's own tile, displacement applied.",
             'CosmeticFootMarks = {', '  dat = "%s",' % md5]
    items = ['[%d]={%s}' % (i, ','.join(str(v) for v in row)) for i, row in rows]
    for k in range(0, len(items), 6):
        lines.append('  ' + ','.join(items[k:k + 6]) + ',')
    lines.append('}')
    lines.append('return CosmeticFootMarks')
    return '\n'.join(lines) + '\n'


def build(dat_path, spr_path):
    dat = Dat(dat_path)
    spr = Spr(spr_path)
    md5 = hashlib.md5(open(dat_path, 'rb').read()).hexdigest()
    rows = []
    for i, t in enumerate(dat.outfits, 1):
        if not t.sprites:
            continue
        row = thing_feet(t, spr)
        if row is not None:
            rows.append((i, row))
    return lua_text(rows, md5), len(rows)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('dat')
    ap.add_argument('spr')
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text, n = build(a.dat, a.spr)
    if a.check:
        have = open(a.out, encoding='utf-8').read() if os.path.exists(a.out) else ''
        if have != text:
            print('%s is not what the pair gives: run %s' % (a.out, os.path.basename(__file__)))
            return 1
        print('foot marks up to date (%d things)' % n)
        return 0
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d things)' % (os.path.relpath(a.out, REPO), n))
    return 0


if __name__ == '__main__':
    sys.exit(main())
