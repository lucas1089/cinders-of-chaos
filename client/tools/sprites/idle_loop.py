# ------------------------------------------------------------------------------------------------------------- helpers
def hash01(seed, a, b):
    """a fixed number in [0, 1) for (seed, a, b): splitmix64 of the three."""
    z = (seed * 0x9E3779B97F4A7C15 + a * 0xBF58476D1CE4E5B9 + b * 0x94D049BB133111EB) & 0xFFFFFFFFFFFFFFFF
    z ^= z >> 30
    z = (z * 0xBF58476D1CE4E5B9) & 0xFFFFFFFFFFFFFFFF
    z ^= z >> 27
    z = (z * 0x94D049BB133111EB) & 0xFFFFFFFFFFFFFFFF
    z ^= z >> 31
    return (z >> 11) / float(1 << 53)


def shift(m, dy, dx, fill=False):
    out = np.full_like(m, fill)
    h, w = m.shape
    ys, yd = (slice(0, h - dy), slice(dy, h)) if dy >= 0 else (slice(-dy, h), slice(0, h + dy))
    xs, xd = (slice(0, w - dx), slice(dx, w)) if dx >= 0 else (slice(-dx, w), slice(0, w + dx))
    out[yd, xd] = m[ys, xs]
    return out


def erode4(m):
    return m & shift(m, 1, 0) & shift(m, -1, 0) & shift(m, 0, 1) & shift(m, 0, -1)


def dilate4(m):
    return m | shift(m, 1, 0) | shift(m, -1, 0) | shift(m, 0, 1) | shift(m, 0, -1)


def mean3(v):
    p = np.pad(v, 1, mode='reflect')
    return sum(p[1 + dy:1 + dy + v.shape[0], 1 + dx:1 + dx + v.shape[1]]
               for dy in (-1, 0, 1) for dx in (-1, 0, 1)) / 9.0


def spread(points, k):
    """k of the points, evenly through the list (the list is in a fixed order)."""
    if not points:
        return []
    k = min(k, len(points))
    return [points[(i * len(points)) // k + (len(points) // k) // 2] for i in range(k)]


def ramp(rgb):
    """dark, mid, light, hot of a colour: hotter is lighter and turned towards yellow."""
    h, s, v = colorsys.rgb_to_hsv(*(c / 255.0 for c in rgb))
    hy = 1 / 6.0
    dh = ((hy - h + 0.5) % 1.0) - 0.5

    def rgb_of(hh, ss, vv):
        return tuple(int(round(c * 255)) for c in colorsys.hsv_to_rgb(hh % 1.0, min(1, max(0, ss)), min(1, max(0, vv))))
    return {'dark': rgb_of(h, s, v * 0.5), 'mid': rgb_of(h, s, v),
            'light': rgb_of(h, s * 0.6, v * 1.2 + 0.15), 'hot': rgb_of(h + dh * 0.3, s * 0.3, 1.0)}


def to_lab(rgb):
    c = np.asarray(rgb, float) / 255.0
    c = np.where(c > 0.04045, ((c + 0.055) / 1.055) ** 2.4, c / 12.92)
    m = np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]])
    xyz = c @ m.T / np.array([0.95047, 1.0, 1.08883])
    f = np.where(xyz > 0.008856, np.cbrt(xyz), 7.787 * xyz + 16 / 116.0)
    return np.stack([116 * f[..., 1] - 16, 500 * (f[..., 0] - f[..., 1]), 200 * (f[..., 1] - f[..., 2])], -1)


def cells_of(h, w):
    """32 px cells of a canvas, as the check counts them"""
    return max(1, (h // 32) * (w // 32))


# ------------------------------------------------------------------------------------------------------------- the sprite
class Sprite:
    """what every layer reads from the still sprite"""

    def __init__(self, a):
        self.a = a
        self.h, self.w = a.shape[:2]
        self.m = a[..., 3] > 0
        hsv = np.array([colorsys.rgb_to_hsv(*(c / 255.0)) for c in a[..., :3].reshape(-1, 3)]).reshape(self.h, self.w, 3)
        self.s, self.v = hsv[..., 1], hsv[..., 2]
        self.edge = self.m & ~erode4(self.m)
        self.top = self.m & ~shift(self.m, 1, 0)
        self.bottom = self.m & ~shift(self.m, -1, 0)
        self.em = self.emissive()
        self.depth = self.depths()
        cols = a[self.m][:, :3]
        self.colours = np.unique(cols, axis=0) if len(cols) else np.zeros((0, 3), np.uint8)
        ys, xs = np.nonzero(self.m)
        self.size = int(max(ys.max() - ys.min(), xs.max() - xs.min()) + 1) if len(ys) else 0
        self.cells = cells_of(self.h, self.w)

    def emissive(self, thr=0.55):
        """saturated, bright pixels brighter than their neighbours, 3 to 12 % of the body: accents only."""
        score = self.s * self.v + (self.v - mean3(self.v))
        area = int(self.m.sum())
        if not area:
            return self.m.copy()
        over = int((self.m & (score > thr)).sum())
        k = int(min(max(over, area * EMISSIVE_SHARE[0], 3), area * EMISSIVE_SHARE[1]))
        k = max(1, min(k, area))
        on = np.sort(score[self.m])[::-1]
        return self.m & (score >= on[k - 1])

    def depths(self):
        """steps from the edge inward (4-connected), 0 on the edge."""
        d = np.full(self.m.shape, -1, int)
        d[self.edge] = 0
        cur, k = self.edge.copy(), 0
        while True:
            nxt = dilate4(cur) & self.m & (d < 0)
            if not nxt.any():
                break
            k += 1
            d[nxt] = k
            cur = nxt
        return d

    def pixels(self, mask):
        """(y, x) of a mask in reading order"""
        ys, xs = np.nonzero(mask)
        return list(zip(ys.tolist(), xs.tolist()))

    def contour(self):
        """the edge pixels in order round the centroid (by angle, then by distance)"""
        pts = self.pixels(self.edge)
        if not pts:
            return []
        cy = sum(p[0] for p in pts) / len(pts)
        cx = sum(p[1] for p in pts) / len(pts)
        return sorted(pts, key=lambda p: (round(math.atan2(p[0] - cy, p[1] - cx), 4), (p[0] - cy) ** 2 + (p[1] - cx) ** 2))


# ---------------------------------------------------------------------------------------------------------------- layers
def parse_colour(s):
    s = s.lstrip('#')
    return tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))


def layer(effect, colour=None, strength=1.0, repeats=1, amount=None):
    if effect not in EFFECTS:
        raise ValueError('unknown effect %s (one of %s)' % (effect, ', '.join(EFFECTS)))
    lo, hi, dflt = AMOUNT.get(effect, (0, 0, 0))
    amt = dflt if amount is None else max(lo, min(hi, int(amount)))
    return {'effect': effect, 'colour': list(colour) if colour else None, 'strength': float(strength),
            'repeats': max(1, int(repeats)), 'amount': amt}


def parse_layer(text):
    parts = text.split(':')
    colour = parse_colour(parts[1]) if len(parts) > 1 and parts[1] else None
    strength = float(parts[2]) if len(parts) > 2 and parts[2] else 1.0
    repeats = int(parts[3]) if len(parts) > 3 and parts[3] else 1
    amount = int(parts[4]) if len(parts) > 4 and parts[4] else None
    return layer(parts[0], colour, strength, repeats, amount)


def element_layers(name):
    effects, colour = ELEMENTS[name]
    return [layer(e, colour) for e in effects]


class Painter:
    """one frame being drawn: float colours, the body, what was added outside it"""

    def __init__(self, sp, soft):
        self.sp = sp
        self.rgb = sp.a[..., :3].astype(float)
        self.alpha = sp.a[..., 3].astype(int)
        self.soft = soft

    def blend(self, mask, c, k):
        if k <= 0:
            return
        k = min(1.0, k)
        self.rgb[mask] += (np.array(c, float) - self.rgb[mask]) * k

    def put(self, y, x, c, glow=False, over_body=True):
        sp = self.sp
        if not (0 <= y < sp.h and 0 <= x < sp.w):
            return
        if sp.m[y, x] and not over_body:
            return
        self.rgb[y, x] = c
        if not sp.m[y, x]:
            self.alpha[y, x] = max(self.alpha[y, x], GLOW if (glow and self.soft) else SOLID)


class Layer:
    def __init__(self, sp, spec, n, seed):
        self.sp, self.spec, self.n, self.seed = sp, spec, n, seed
        col = spec['colour']
        if col is None:
            em = sp.a[sp.em][:, :3]
            col = tuple(int(v) for v in np.median(em, axis=0)) if len(em) else (255, 220, 140)
        self.colour = tuple(col)
        self.r = ramp(self.colour)
        self.amount = spec['amount']
        sources = sp.pixels(sp.em if spec['effect'] == 'motes' else sp.top)
        if spec['effect'] == 'motes' and len(sources) < self.amount:
            sources = sp.pixels(sp.top)
        if spec['effect'] == 'glint':
            sources = self.glint_sources()
            m = max(1, n // 3)                                    # events of each glint: 3 frames (4 or 5 to fill)
            self.events = [(j * n) // m for j in range(m + 1)]
        if spec['effect'] == 'drip':
            sources = self.drip_sources()
        self.points = spread(sources, max(1, self.amount))
        if spec['effect'] == 'glint':
            k = max(1, self.amount) * (len(self.events) - 1)
            many = spread(sources, k)
            self.points = [many[i % len(many)] for i in range(k)]
        self.ring = sp.contour() if spec['effect'] == 'rim' else []
        if spec['effect'] == 'frost':
            d = sp.depth.astype(float)
            noise = np.array([[hash01(seed, y, x) for x in range(sp.w)] for y in range(sp.h)])
            self.order = np.where(sp.m, d + 1.5 * noise, np.inf)
            self.reach = float(d.max() + 1) * 0.6 + 1.0
        if spec['effect'] == 'flames':
            self.ytop = {}
            for y, x in sp.pixels(sp.top):
                if x not in self.ytop or y < self.ytop[x]:
                    self.ytop[x] = y
            xs = sorted(self.ytop)
            run_end = {}
            for x in xs:
                left = 0
                while x - left - 1 in self.ytop:
                    left += 1
                right = 0
                while x + right + 1 in self.ytop:
                    right += 1
                run_end[x] = min(left, right)
            self.taper = {x: min(1.0, (run_end[x] + 1) / 2.5) for x in xs}
            self.phase = {x: (hash01(seed, x, 1), hash01(seed, x, 2)) for x in xs}

    def glint_sources(self):
        """accents first, then the rest of the body (brightest first), only pixels the hot colour stands out from"""
        sp = self.sp
        lab = to_lab(sp.a[..., :3].astype(float))
        far = sp.m & (np.sqrt(((lab - to_lab(np.array(self.r['hot'], float))) ** 2).sum(-1)) >= GLINT_DE)
        acc = sp.pixels(far & sp.em)
        if len(acc) < self.amount:
            rest = sp.pixels(far & ~sp.em & ~sp.edge) or sp.pixels(far & ~sp.em)
            rest.sort(key=lambda p: (-round(float(sp.v[p]), 4), p))
            acc = sorted(acc + rest[:max(0, self.amount - len(acc)) * 8])
        if not acc:
            raise ValueError('glint: no pixel of the body differs from the glint colour by %g (Lab), the glint would '
                             'not show: give another colour or another effect' % GLINT_DE)
        return acc

    def drip_sources(self):
        """bottom edge pixels with DRIP_ROOM clear rows under them (falling drops); else top edge pixels over a
        column of DRIP_ROOM body rows (drops running down the face); else refused"""
        sp = self.sp
        free, self.run = [], {}
        for y, x in sp.pixels(sp.bottom):
            room = 0
            while y + room + 1 < sp.h and not sp.m[y + room + 1, x]:
                room += 1
            if room >= DRIP_ROOM:
                free.append((y, x))
                self.run[(y, x)] = room
        if free:
            self.face = False
            return free
        face = []
        for y, x in sp.pixels(sp.top):
            run = 0
            while y + run + 1 < sp.h and sp.m[y + run + 1, x]:
                run += 1
            if run >= DRIP_ROOM:
                face.append((y, x))
                self.run[(y, x)] = run
        if not face:
            raise ValueError('drip: no room under the body (%d clear rows) and no column of %d body rows to run down; '
                             'give the sprite room below (a taller canvas) or pick another effect'
                             % (DRIP_ROOM, DRIP_ROOM))
        self.face = True
        return face

    def pulse_levels(self, times):
        """the blend weights the pulse reaches at the loop's frames (0 left out)"""
        n, r = self.n, self.spec['repeats']
        ps = sorted({round((1 - math.cos(TAU * ((t * r) % n) / float(n))) / 2, 9) for t in times})
        return [p for p in ps if p > 0]

    def pulse_steps(self, times):
        """the colours the pulse makes, one group a source colour (accents by count, then the ring): ramp steps"""
        sp = self.sp
        light = np.array(self.r['light'], float)
        levels = self.pulse_levels(times)
        halo = dilate4(sp.em) & sp.m & ~sp.em
        groups = []
        for mask, k in ((sp.em, 0.6), (halo, 0.25)):
            cols, cnt = np.unique(sp.a[mask][:, :3], axis=0, return_counts=True)
            for i in sorted(range(len(cols)), key=lambda j: (-cnt[j], tuple(int(v) for v in cols[j]))):
                c = cols[i].astype(float)
                groups.append([tuple(int(v) for v in np.floor(c + (light - c) * min(1.0, k * p) + 0.5).clip(0, 255))
                               for p in levels])
        return groups

    def apply(self, pt, t):
        n, e = self.n, self.spec['effect']
        ph = (t % n) / float(n)
        getattr(self, e)(pt, t % n, ph)

    # ---- effects ----
    def pulse(self, pt, t, ph):
        sp, p = self.sp, (1 - math.cos(TAU * ph)) / 2
        halo = dilate4(sp.em) & sp.m & ~sp.em
        pt.blend(sp.em, self.r['light'], 0.6 * p)
        pt.blend(halo, self.r['light'], 0.25 * p)

    GLINT_SHAPES = ('plus', 'star', 'fade', 'x', 'dot')

    def glint(self, pt, t, ph):
        """`amount` glints lit in every frame; each lives 3 frames (4 or 5 where the loop does not split in threes):
        a plus, a star (arms of 2 and the diagonals), the plus fading; then it lights at the next point"""
        n, ev, amt = self.n, self.events, max(1, self.amount)
        m = len(ev) - 1
        for i in range(amt):
            u = (t - (i * n) // (amt * m)) % n                   # tracks offset inside an event
            j = max(k for k in range(m) if ev[k] <= u)
            y, x = self.points[j * amt + i]
            shape = self.GLINT_SHAPES[min(u - ev[j], len(self.GLINT_SHAPES) - 1)]
            hot, light, mid = self.r['hot'], self.r['light'], self.r['mid']
            pt.put(y, x, hot if shape != 'fade' else light)
            arms = {'plus': ((1, light),), 'star': ((1, light), (2, light)), 'fade': ((1, mid),)}.get(shape, ())
            for d, c in arms:
                for dy, dx in ((d, 0), (-d, 0), (0, d), (0, -d)):
                    pt.put(y + dy, x + dx, c)
            if shape in ('star', 'x'):
                for dy, dx in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
                    pt.put(y + dy, x + dx, light if shape == 'star' else mid)

    def shine(self, pt, t, ph):
        sp = self.sp
        if ph >= 0.5:
            return
        yy, xx = np.mgrid[0:sp.h, 0:sp.w]
        d = yy + xx
        hw = self.shine_half()
        lo, hi = int(d[sp.m].min()) - 1 - hw, int(d[sp.m].max()) + 1 + hw
        pos = lo + int((hi - lo) * ph * 2)
        pt.blend(sp.m & (np.abs(d - pos) <= hw), self.r['light'], 0.55)
        pt.blend(sp.m & (np.abs(d - pos) <= hw // 3), self.r['hot'], 0.5)

    def shine_half(self):
        """half width of the shine band: 6 % of the body's diagonal, at least 1 (3 px on a small item)"""
        sp = self.sp
        d = np.mgrid[0:sp.h, 0:sp.w].sum(0)[sp.m]
        return max(1, int(round(0.06 * (int(d.max()) - int(d.min())))))

    def rim_thick(self):
        """rows of the rim band: 1 on a body under 16 px, one more each 16 px"""
        return 1 + self.sp.size // 16

    def motes(self, pt, t, ph):
        sp, n = self.sp, self.n
        rise = max(4, min(sp.h // 2, 14))
        for i, (y0, x0) in enumerate(self.points):
            off = (i * n) // max(1, len(self.points))
            age = (t + off) % n
            y = y0 - 1 - (age * rise) // n
            x = x0 + int(round(math.sin(TAU * age / n + i)))
            for k, key in enumerate(('hot', 'light', 'mid')):
                pt.put(y + k, x, self.r[key], glow=(key == 'mid'))

    def flames(self, pt, t, ph):
        sp, n = self.sp, self.n
        height = float(self.amount)
        for x, yt in self.ytop.items():
            a, b = self.phase[x]
            h = height * self.taper[x] * (0.55 + 0.25 * math.sin(TAU * (ph + x * 0.31 + a))
                                          + 0.2 * math.sin(TAU * (2 * ph - x * 0.53 + b)))
            top = int(round(h))
            for d in range(1, top + 1):
                y = yt - d
                if y < 0 or sp.m[y, x]:
                    break
                remain = h - d
                if remain < 1.0 and hash01(self.seed, x, (y + t) % n) < 0.35:
                    break                                         # a torn tip, scrolling up one row a frame
                key = 'hot' if remain >= 3 else 'light' if remain >= 2 else 'mid' if remain >= 1 else 'dark'
                pt.put(y, x, self.r[key], glow=(key == 'dark'), over_body=False)
        lit = np.zeros_like(sp.m)
        for x, yt in self.ytop.items():
            lit[yt, x] = True
        pt.blend(lit, self.r['light'], 0.35)

    def frost(self, pt, t, ph):
        sp = self.sp
        p = (1 - math.cos(TAU * ph)) / 2
        front = self.reach * p
        frozen = self.order < front
        pt.blend(frozen, self.r['light'], 0.5)
        pt.blend(frozen & (self.order >= front - 1.0), self.r['hot'], 0.55)

    def drip(self, pt, t, ph):
        sp, n = self.sp, self.n
        for i, (y0, x0) in enumerate(self.points):
            off = (i * n) // max(1, len(self.points))
            q = ((t + off) % n) / float(n)
            if q < 0.4:
                tip = np.zeros_like(sp.m)
                tip[y0, x0] = True
                pt.blend(tip, self.r['light'], 0.3 + q)
                continue
            run = self.run[(y0, x0)]
            if self.face:                                         # down the face, over the body: colours only
                y = y0 + int((q - 0.4) / 0.6 * (run + 1))
                for k, key in enumerate(('mid', 'light', 'hot')):
                    if y0 <= y - 2 + k <= y0 + run:
                        pt.put(y - 2 + k, x0, self.r[key])
                continue
            y = y0 + 1 + int((q - 0.4) / 0.6 * run)
            for k, key in enumerate(('mid', 'light', 'hot')):
                if y + k <= y0 + run:
                    pt.put(y + k, x0, self.r[key], over_body=False)

    def rim(self, pt, t, ph):
        ring = self.ring
        L = len(ring)
        if not L:
            return
        sp = self.sp
        seg = max(3, L // 6)
        thick = self.rim_thick()
        band = np.zeros_like(sp.m)
        heads = []
        for j in range(max(1, self.amount)):
            pos = int(ph * L) + (j * L) // max(1, self.amount)
            for k in range(seg):
                y, x = ring[(pos - k) % L]
                band[y, x] = True
                heads.append((y, x, k == 0))
        if thick > 1:
            inner = band
            for _ in range(thick - 1):
                inner = dilate4(inner)
            pt.blend(inner & sp.m & (sp.depth < thick) & ~band, self.r['light'], 0.7)
        for y, x, head in heads:
            pt.put(y, x, self.r['hot'] if head else self.r['light'])


