#!/usr/bin/env python3
"""The official module digest list for the bot detection's integrity check (O722; server/README.md "Bot detection events and scores
(O722)", docs/BOT_DETECTION.md part 4).

The main client sends the digest of every folder of modules/ and mods/ at login (client module game_chaosguard, integrity.lua); the
server (data/scripts/chaos/botdet.lua) compares them with the list this script writes at release and records the extras and the
changes as `integrity` events for staff to read. Nothing is closed or banned by it.

The rule, the same as integrity.lua's (client/tools/gen_module_hashes_test.py holds both to one fixture):
  * the files of a folder modules/<name> or mods/<name>, recursively, that end in .lua .otui .otmod .otml .json (any case)
  * one text line a file: "<path relative to the module folder, with />:<sha256 of the file, lower case hex>\\n"
  * the lines sorted as text (byte order of the UTF-8), joined, and the SHA-256 of that text is the module's digest
  * the key is the folder name; the mods folder's keys have "mods/" before the name

  python3 -I client/tools/gen_module_hashes.py CLIENT_DIR [--build N] [--out FILE]   # write server/data/lib/chaos_module_hashes.lua
  python3 -I client/tools/gen_module_hashes.py CLIENT_DIR --check [--out FILE]       # exit 1 when FILE is not what CLIENT_DIR gives

CLIENT_DIR is the assembled client tree (client/tools/assemble_client.sh output) or the tree the release is cut from: the one with
modules/ and mods/ in it, with the files the player really gets (the overlay on top of the base files). The build number defaults to
the one in CLIENT_DIR/chaos_build.txt when it has one.
"""
import hashlib
import os
import re
import sys

EXTS = {'lua', 'otui', 'otmod', 'otml', 'json'}
ROOTS = ('modules', 'mods')
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, '..', '..', 'server', 'data', 'lib', 'chaos_module_hashes.lua')
HEADER = ('-- The official module digests of the client (generated by client/tools/gen_module_hashes.py at release; do not edit by hand).\n'
          '-- Read by data/scripts/chaos/botdet.lua: a module the client sends that is not here is an extra, one with another digest is\n'
          '-- changed (an `integrity` event for staff, never an action). An empty list compares nothing.\n')


def file_sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 16), b''):
            h.update(block)
    return h.hexdigest()


def sha_text(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def module_files(base):
    """relative paths (with /) of the counted files under one module folder"""
    out = []
    for d, dirs, files in os.walk(base):
        dirs.sort()
        for n in sorted(files):
            ext = n.rsplit('.', 1)[-1].lower() if '.' in n else ''
            if ext in EXTS:
                out.append(os.path.relpath(os.path.join(d, n), base).replace(os.sep, '/'))
    return out


def digests(client_dir, hash_file=file_sha256, sha=sha_text):
    """{key: digest} of every module folder of the tree"""
    out = {}
    for root in ROOTS:
        top = os.path.join(client_dir, root)
        if not os.path.isdir(top):
            continue
        for name in sorted(os.listdir(top)):
            base = os.path.join(top, name)
            if not os.path.isdir(base):
                continue
            lines = []
            for rel in module_files(base):
                lines.append('%s:%s\n' % (rel, hash_file(os.path.join(base, rel)).lower()))
            if lines:
                lines.sort(key=lambda s: s.encode('utf-8'))
                out[name if root == 'modules' else 'mods/' + name] = sha(''.join(lines))
    return out


def render(digs, build):
    body = ''.join('\t\t[%s] = "%s",\n' % ('"' + k.replace('\\', '\\\\').replace('"', '\\"') + '"', digs[k]) for k in sorted(digs))
    return HEADER + 'return {\n\tbuild = %d,\n\tmodules = {\n%s\t}\n}\n' % (build, body)


def read_build(client_dir):
    p = os.path.join(client_dir, 'chaos_build.txt')
    if os.path.exists(p):
        m = re.search(r'\d+', open(p, encoding='utf-8').read())
        if m:
            return int(m.group(0))
    return 0


def main(argv):
    args = list(argv)
    check = '--check' in args
    if check:
        args.remove('--check')
    out = DEFAULT_OUT
    build = None
    if '--out' in args:
        i = args.index('--out')
        out = args[i + 1]
        del args[i:i + 2]
    if '--build' in args:
        i = args.index('--build')
        build = int(args[i + 1])
        del args[i:i + 2]
    if len(args) != 1 or not os.path.isdir(args[0]):
        print(__doc__.split('\n\n')[0])
        print('usage: gen_module_hashes.py CLIENT_DIR [--build N] [--out FILE] [--check]')
        return 2
    digs = digests(args[0])
    if not digs:
        print('no module folder with code files under %s/modules or /mods' % args[0])
        return 1
    text = render(digs, build if build is not None else read_build(args[0]))
    if check:
        have = open(out, encoding='utf-8').read() if os.path.exists(out) else ''
        if have != text:
            print('%s is not what %s gives: run without --check' % (out, args[0]))
            return 1
        print('module hashes ok: %d modules' % len(digs))
        return 0
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d modules' % (out, len(digs)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
