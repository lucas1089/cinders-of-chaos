#!/usr/bin/env python3
"""Credits data from docs/CREDITS.md (the single source of truth; its header explains the format).

Writes
  client/overlay/modules/client_chaos_credits/credits_data.lua   ChaosCreditsData, the in-game Credits window
  website/overlay/plugins/chaos/credits/credits_data.json         the website Credits page

  python3 -I client/tools/gen_credits.py           # write both files
  python3 -I client/tools/gen_credits.py --check   # fail when either file is not up to date (CI)

Only the part between `<!-- credits:begin -->` and `<!-- credits:end -->` is read. The Lua file is ASCII: every
other character is a cp1252 decimal escape, the encoding the client's fonts draw (client/MANIFEST.md "OFL fonts").
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'docs', 'CREDITS.md')
LUA_OUT = os.path.join(ROOT, 'client', 'overlay', 'modules', 'client_chaos_credits', 'credits_data.lua')
JSON_OUT = os.path.join(ROOT, 'website', 'overlay', 'plugins', 'chaos', 'credits', 'credits_data.json')

BEGIN, END = '<!-- credits:begin -->', '<!-- credits:end -->'
FIELDS = {'author': 'author', 'licence': 'licence', 'credit': 'credit', 'used for': 'use', 'source': 'source'}
FIELD_ORDER = ('name', 'author', 'licence', 'credit', 'use', 'source')
HEADING = re.compile(r'^##\s+(.+?)\s*\{pt-BR:\s*(.+?)\s*\}\s*$')
ENTRY = re.compile(r'^-\s+\*\*(.+?)\*\*\s*$')
FIELD = re.compile(r'^\s+-\s+([A-Za-z ]+):\s*(.+?)\s*$')


class CreditsError(ValueError):
    pass


def plain(text):
    """Markdown inline code and bold marks dropped: the client and the page show plain text."""
    return re.sub(r'\*\*|`', '', text).strip()


def shown_part(text):
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise CreditsError('docs/CREDITS.md needs one credits:begin marker before one credits:end marker')
    return text[text.index(BEGIN) + len(BEGIN):text.index(END)]


def parse(text):
    """The shown sections: [{title, pt, note, entries: [{name, author, licence, credit, use, source}]}]."""
    sections = []
    section = entry = None
    note = []

    def close_note():
        if section is not None and note:
            joined = ' '.join(note)
            section['note'] = (section['note'] + ' ' + joined).strip() if section['note'] else joined
        del note[:]

    for no, raw in enumerate(shown_part(text).split('\n'), 1):
        line = raw.rstrip()
        if not line.strip():
            close_note()
            continue
        if line.startswith('#'):
            close_note()
            m = HEADING.match(line)
            if not m:
                raise CreditsError(f'line {no}: a heading needs the form "## Title {{pt-BR: Título}}": {line}')
            section = {'title': plain(m.group(1)), 'pt': plain(m.group(2)), 'note': '', 'entries': []}
            sections.append(section)
            entry = None
            continue
        if section is None:
            raise CreditsError(f'line {no}: text before the first heading: {line}')
        m = ENTRY.match(line)
        if m:
            close_note()
            entry = {'name': plain(m.group(1))}
            section['entries'].append(entry)
            continue
        m = FIELD.match(line)
        if m and entry is not None:
            key = FIELDS.get(m.group(1).strip().lower())
            if key is None:
                raise CreditsError(f'line {no}: unknown field {m.group(1)!r} (known: {", ".join(FIELDS)})')
            if key in entry:
                raise CreditsError(f'line {no}: {m.group(1)} given twice for {entry["name"]}')
            entry[key] = plain(m.group(2))
            continue
        if line.startswith((' ', '-')):
            raise CreditsError(f'line {no}: not an entry or a field: {line}')
        entry = None
        note.append(plain(line))
    close_note()
    if not sections:
        raise CreditsError('docs/CREDITS.md shows no section')
    for s in sections:
        if not s['entries'] and not s['note']:
            raise CreditsError(f'section {s["title"]!r} is empty')
    return sections


def lua_string(text):
    out = ['"']
    for ch in text:
        if ch in '"\\':
            out.append('\\' + ch)
        elif ' ' <= ch <= '~':
            out.append(ch)
        else:
            try:
                b = ch.encode('cp1252')
            except UnicodeEncodeError:
                raise CreditsError(f'{ch!r} has no cp1252 code (the client cannot draw it): {text}')
            out.append(''.join('\\%03d' % x for x in b))
    out.append('"')
    return ''.join(out)


def lua_data(sections):
    lines = ['-- Generated by client/tools/gen_credits.py from docs/CREDITS.md. Do not edit: edit docs/CREDITS.md and run',
             '-- python3 -I client/tools/gen_credits.py. Text in cp1252 (the client fonts\' encoding).',
             'ChaosCreditsData = {']
    for s in sections:
        lines.append('  {')
        lines.append(f'    title = {lua_string(s["title"])},')
        lines.append(f'    pt = {lua_string(s["pt"])},')
        lines.append(f'    note = {lua_string(s["note"])},')
        lines.append('    entries = {')
        for e in s['entries']:
            parts = [f'{k} = {lua_string(e[k])}' for k in FIELD_ORDER if k in e]
            lines.append('      { ' + ', '.join(parts) + ' },')
        lines.append('    },')
        lines.append('  },')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def json_data(sections):
    ordered = [{'title': s['title'], 'pt': s['pt'], 'note': s['note'],
                'entries': [{k: e[k] for k in FIELD_ORDER if k in e} for e in s['entries']]} for s in sections]
    return json.dumps({'generator': 'client/tools/gen_credits.py', 'source': 'docs/CREDITS.md', 'sections': ordered},
                      ensure_ascii=False, indent=1) + '\n'


def outputs(text):
    sections = parse(text)
    return {LUA_OUT: lua_data(sections), JSON_OUT: json_data(sections)}


def main(argv):
    check = '--check' in argv
    try:
        with open(SOURCE, encoding='utf-8') as f:
            files = outputs(f.read())
    except CreditsError as e:
        print(f'gen_credits: {e}')
        return 1
    stale = 0
    for path, content in files.items():
        rel = os.path.relpath(path, ROOT)
        old = None
        if os.path.exists(path):
            with open(path, encoding='utf-8') as f:
                old = f.read()
        if old == content:
            continue
        if check:
            print(f'gen_credits: {rel} is not up to date with docs/CREDITS.md (run python3 -I client/tools/gen_credits.py)')
            stale += 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(content)
            print(f'gen_credits: wrote {rel}')
    if check:
        print('credits data:', 'OK' if not stale else f'{stale} stale file(s)')
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
