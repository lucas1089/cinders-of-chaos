	{2278, {25, 50, 100}, "Slows a target down a lot."}, -- Shackle
	{2261, {100, 250}, "Removes a magic field."} -- Dispel
}
local okRunes, RUNES = pcall(dofile, "data/lib/chaos_rune_supply.lua")
local function runeOffers()
	local out = {}
	if not okRunes or type(RUNES) ~= "table" then
		return out
	end
	for _, p in ipairs(RUNE_PACKS) do
		local r
		for _, x in ipairs(RUNES.runes or {}) do
			if x.id == p[1] then
				r = x
			end
		end
		if r then
			for _, n in ipairs(p[2]) do
				local pct = RUNE_DISCOUNT[n] or 0
				local cost = math.max(1, math.ceil(r.price * n * (100 - pct) / 100 / RUNE_GOLD_PER_COIN))
				out[#out + 1] = {kind = "item", id = r.id, count = n, cost = cost, overflowInbox = true,
					name = n .. " " .. r.name .. "s", description = p[3] .. (pct > 0 and (" " .. pct .. "% off the 100 pack.") or "")}
			end
		end
	end
	return out
end

