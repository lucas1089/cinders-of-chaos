local POTION_SIZES = {100, 250, 500}

local function potionOffers()
	local out = {}
	for _, p in ipairs(POTION_PACKS) do
		for _, n in ipairs(POTION_SIZES) do
			local pct = RUNE_DISCOUNT[n] or 0
			local cost = math.ceil(p[2] * n / 100 * (100 - pct) / 100)
			out[#out + 1] = {kind = "item", id = p[1], count = n, cost = cost,
				name = n .. " " .. p[3], description = p[4] .. (pct > 0 and (" " .. pct .. "% off the 100 pack.") or "")}
		end
	end
	return out
end

local function runeOffers()
	local out = {}
	if not okRunes or type(RUNES) ~= "table" then
		return out
	end
	for _, p in ipairs(RUNE_PACKS) do
		local r
		for _, x in ipairs(RUNES.runes or {}) do
			if x.id == p[1] then
				r = x
			end
		end
		if r then
			for _, n in ipairs(p[2]) do
				local pct = RUNE_DISCOUNT[n] or 0
				local cost = math.max(1, math.ceil(r.price * n * (100 - pct) / 100 / RUNE_GOLD_PER_COIN))
				out[#out + 1] = {kind = "item", id = r.id, count = n, cost = cost, overflowInbox = true,
					name = n .. " " .. r.name .. "s", description = p[3] .. (pct > 0 and (" " .. pct .. "% off the 100 pack.") or "")}
			end
		end
	end
	return out
end

-- ------------------------------------------------------------------ the category tree
-- The parents (`groups` below) hold subcategories; a category names its parent in `parent` and stands under it in
-- config order (ChaosShopCore.arrange). A category without `parent` is a top category (Starter, This week, Bundles,
-- Crafting). Add a subcategory: a category table with parent = P_COSMETICS (or another parent) at the place it should
-- stand, or, from another file, ChaosShopCore.addSubcategory(cfg, "Cosmetics", category, "Auras").
local P_PREMIUM, P_CONSUMABLES, P_COSMETICS = "Premium & Services", "Consumables", "Cosmetics"

-- a category built elsewhere (cosmetics_store.lua, pact_config.lua ...) under a parent
local function under(parent, category)
	category.parent = parent
	return category
end

-- list with the offers of more appended
local function append(list, more)
	for _, o in ipairs(more or {}) do
		list[#list + 1] = o
	end
	return list
end

