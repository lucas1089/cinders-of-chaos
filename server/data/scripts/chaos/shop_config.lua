--       (nameplate.lua), bought once
--   {kind = "unlock", unlock = "transmog_<set key>", ...}  a transmog appearance set, per account (transmog.lua)
--   {kind = "unlock", unlock = "cosmetic_<key>", ...}  a cosmetic, per account (cosmetics.lua, cosmetics_store.lua)
--   {kind = "bundle", parts = {<offer key> | <offer table>, ...}, pct = n | cost = n}   several offers at once, at
--       pct % off their list prices (or a fixed cost); refused when one part is owned or cannot apply now
--   {kind = "pact", days = n}  (bundle part only) days of the Chaos Pact when that system is loaded (`pact` below);
--       without it the part is left out of the bundle
-- Optional offer fields:
--   key            stable id (default ChaosShopCore.offerKey: "wings:4", "outfit:909", "item:29856x10", ...); sales,
--                  featured lists, bundles, limits and the purchase log use it. Never reuse a key for something else.
--   weeklyLimit    purchases per account per week (weeks start Monday, storefront.weekHour)
--   seasonBlocked  season characters cannot buy it (season.lua realm > 0)
--   oncePerAccount bought once per account (purchase log); hidden afterwards
--   maxLevel       hidden from (and refused to) characters above this level
--   gift = false   not giftable (kinds outside ChaosShopCore.GIFTABLE never are)
--   noSale         sales and the featured discount leave it alone
-- Names, descriptions and the category icon are what the client shows. Cosmetics without a name take
-- the one from their XML file. Outfits, outfit addons and mounts come from shop_cosmetics.lua (generated by
-- server/tools/gen_shop_cosmetics.py from the base XML, exclusives left out; shop.lua checks them again at load).

