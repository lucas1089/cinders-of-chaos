local function generated(list, kind, describe)
	local out = {}
	for i, e in ipairs(list) do
		local o = {}
		for k, v in pairs(e) do
			o[k] = v
		end
		o.kind = kind
		o.description = o.description or describe(e)
		out[i] = o
	end
	return out
end

local function premiumNote(e)
	return e.premium and " Premium account needed to wear it." or ""
end

local function preview(extra)
	local o = {}
	for k, v in pairs(PREVIEW) do
		o[k] = v
	end
	for k, v in pairs(extra or {}) do
		o[k] = v
	end
	o.rotating = true
	return o
end

