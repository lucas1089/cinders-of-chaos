-- the store's categories: slug -> (offer kind, category name, the piece the category icon shows)
M.CATEGORIES = {
	{slug = "heads", name = "Head Accessories", icon = "head_bone_crown"},
	{slug = "capes", name = "Capes", icon = "cape_raven_feather_cape"}
}

local ELEMENT = {fire = "Fire", water = "Water", wind = "Wind", earth = "Earth", energy = "Storm", light = "Light",
	dark = "Dark", neutral = "Plain"}

local function exclusiveKeys()
	local out = {}
	for _, e in ipairs(M.exclusives) do
		out[e.key] = e
	end
	for _, e in ipairs(M.founder) do
		out[e.key] = e
	end
	return out
end

-- a piece by key (any of the three lists) and its kind ("wings" or "aura")
function M.piece(key)
	for _, slug in ipairs({"wings", "heads", "capes"}) do
		for _, p in ipairs(M.data[slug] or {}) do
			if p.key == key then
				return p, slug == "wings" and "wings" or "aura"
			end
		end
	end
	return nil
end

local function describe(slug, p)
	local el = ELEMENT[p.element] or "Plain"
	if slug == "wings" then
		return el .. " wings, animated. Wear them with any aura, head accessory or cape."
	end
	local what = slug == "heads" and "head accessory" or "cape"
	return el .. " " .. what .. ", animated. It takes the aura slot: one aura, head accessory or cape at a time."
end

-- the store offers of one list ("wings", "heads", "capes"), the exclusives left out; empty while the switch is off
function M.storeOffers(slug)
	local out = {}
	if not M.PAIR33 then
		return out
	end
	local ex = exclusiveKeys()
	for _, p in ipairs(M.data[slug] or {}) do
		if not ex[p.key] then
			out[#out + 1] = {kind = slug == "wings" and "wings" or "aura", id = p.id, cost = p.cost,
				description = describe(slug, p)}
		end
	end
	return out
end

-- shop_config.lua: the Wings offers go at the end of its Wings category; the two new categories are subcategories of
-- `parent` (the store tree's "Cosmetics") right after Auras, Head Accessories then Capes (ChaosShopCore.addSubcategory
-- when loaded, the same placement by hand otherwise). `preview` is shop_config.lua's icon helper (the store's preview
-- look with this aura). None while off.
function M.addStore(cfg, preview, parent)
	if not M.PAIR33 then
		return cfg
	end
	parent = parent or "Cosmetics"
	for _, c in ipairs(cfg.categories or {}) do
		if c.name == "Wings" then
			for _, o in ipairs(M.storeOffers("wings")) do
				c.offers[#c.offers + 1] = o
			end
		end
	end
	local after = "Auras"
	for _, c in ipairs(M.CATEGORIES) do
		local icon = M.piece(c.icon)
		local cat = {name = c.name,
			icon = icon and {outfit = preview and preview({aura = icon.look}) or {type = 128, aura = icon.look}} or nil,
			offers = M.storeOffers(c.slug)}
		if ChaosShopCore and ChaosShopCore.addSubcategory then
			ChaosShopCore.addSubcategory(cfg, parent, cat, after)
		else
			cat.parent = parent
			local at = #cfg.categories
			for i, x in ipairs(cfg.categories) do
				if x.name == after then
					at = i
				end
			end
			table.insert(cfg.categories, at + 1, cat)
		end
		after = c.name
	end
	return cfg
end

-- exclusives_config.lua: the exclusives and their boss groups, only when on
function M.addExclusives(cfg)
	if not M.PAIR33 then
		return cfg
	end
	local byBoss = {}
	for _, e in ipairs(M.exclusives) do
		local p, kind = M.piece(e.key)
		if p then
			cfg.exclusives[#cfg.exclusives + 1] = {key = e.key, kind = kind, id = p.id, look = p.look, icon = e.icon,
				source = "boss", name = p.name, desc = e.desc}
			byBoss[e.boss] = byBoss[e.boss] or {}
			table.insert(byBoss[e.boss], e.key)
		end
	end
	for _, b in ipairs(cfg.bosses or {}) do
		for _, key in ipairs(byBoss[b.key] or {}) do
			b.rewards[#b.rewards + 1] = key
		end
	end
	-- the Founder Pack pieces: source "founder", no boss group
	for _, e in ipairs(M.founder) do
		local p, kind = M.piece(e.key)
		if p then
			cfg.exclusives[#cfg.exclusives + 1] = {key = e.key, kind = kind, id = p.id, look = p.look, icon = e.icon,
				source = "founder", name = p.name, desc = e.desc}
		end
	end
	return cfg
end

return M
