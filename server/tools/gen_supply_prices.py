#!/usr/bin/env python3
"""Build the supply price table of the hunt tracker (data/scripts/chaos/hunt_supplies.lua).

usage: python3 -I gen_supply_prices.py DATA_DIR [OUT_FILE]

Supplies are the items a hunt uses up: potions (name ends in "potion", not flasks), runes (items.xml type "rune"),
and ammunition (weaponType "ammunition"; none is sold once tools/patch_base_archery.py ran). Thrown distance weapons
are no supply any more: the stackable throwing weapons left the game (data/lib/chaos_throwables.lua). The price is what the player pays an NPC for one unit, read from every NPC of the base
server (the same sources as gen_sell_prices.py, buy side):
  - data/npc/*.xml           <parameter key="shop_buyable" value="name,id,price[,subtype];..."/>
  - data/npc/scripts/*.lua   shopModule:addBuyableItem({...}, id, price[, subtype], ...)
                             {name = '...', id = 1234, ..., buy = 75} tables
The lowest price any NPC asks wins. The price is per item: runes are stackable in this protocol, so the subtype (the
charges an NPC writes on a rune) does not change the price of one rune. Unscribed runes, recipe formulas and the staff test NPCs are skipped. Supplies no NPC sells are left out (the tracker then counts them at 0 gold). The output is a plain Lua
table ({[server item id] = gold per unit}), sorted by id, so it can be kept in the repo.
"""
import glob, os, re, sys

XML_PARAM = re.compile(r'key\s*=\s*"shop_buyable"\s+value\s*=\s*"([^"]*)"', re.S)
LUA_ADD = re.compile(r'addBuyableItem\s*\(\s*(?:\{[^}]*\}|nil|"[^"]*"|\'[^\']*\')\s*,\s*(\d+)\s*,\s*(\d+)(?:\s*,\s*(\d+))?')
LUA_TABLE = re.compile(r'\{[^{}]*?\bid\s*=\s*(\d+)[^{}]*?\bbuy\s*=\s*(\d+)[^{}]*?\}')
ITEM = re.compile(r'<item\s+([^>]*?)(/?)>(.*?)(?:</item>|(?=<item\s))', re.S)
ATTR = re.compile(r'(\w+)\s*=\s*"([^"]*)"')
KEYVAL = re.compile(r'<attribute\s+key\s*=\s*"([^"]+)"\s+value\s*=\s*"([^"]*)"')


def read(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return f.read()


def supply_ids(data_dir):
    """Server ids of the supply items in items.xml."""
    ids = set()
    for m in ITEM.finditer(read(os.path.join(data_dir, 'items', 'items.xml'))):
        head = dict(ATTR.findall(m.group(1)))
        body = '' if m.group(2) else m.group(3)
        attrs = {k.lower(): v.lower() for k, v in KEYVAL.findall(body)}
        name = head.get('name', '').lower().strip()
        weapon = attrs.get('weapontype', '')
        supply = (
            (name.endswith(' potion') and not name.startswith(('formula', 'empty')))
            or attrs.get('type') == 'rune'
            or weapon == 'ammunition'
        )
        if not supply or name.startswith(('unscribed', 'blank')):
            continue
        if 'id' in head and head['id'].isdigit():
            ids.add(int(head['id']))
        elif head.get('fromid', '').isdigit() and head.get('toid', '').isdigit():
            ids.update(range(int(head['fromid']), int(head['toid']) + 1))
    return ids


def npc_files(data_dir, pattern):
    """NPC files, without the staff test NPCs (a file name containing "test" sells at token prices)."""
    return [p for p in sorted(glob.glob(os.path.join(data_dir, 'npc', pattern)))
            if 'test' not in os.path.basename(p).lower()]


def collect(data_dir):
    wanted = supply_ids(data_dir)
    prices = {}

    def put(item_id, price, subtype=0):
        if item_id not in wanted or price <= 0:
            return
        per = price
        if per < prices.get(item_id, 1 << 62):
            prices[item_id] = per

    for path in npc_files(data_dir, '*.xml'):
        for value in XML_PARAM.findall(read(path)):
            for entry in value.split(';'):
                parts = [p.strip() for p in entry.split(',')]
                if len(parts) < 3 or not parts[1].isdigit() or not parts[2].isdigit():
                    continue
                sub = int(parts[3]) if len(parts) >= 4 and parts[3].isdigit() else 0
                put(int(parts[1]), int(parts[2]), sub)
    for path in npc_files(data_dir, os.path.join('scripts', '*.lua')):
        text = read(path)
        for item_id, price, sub in LUA_ADD.findall(text):
            put(int(item_id), int(price), int(sub) if sub else 0)
        for item_id, price in LUA_TABLE.findall(text):
            put(int(item_id), int(price))
    return prices


def render(prices):
    lines = [
        '-- Supply prices of the hunt tracker (hunt.lua). GENERATED by server/tools/gen_supply_prices.py from the base',
        '-- server\'s NPC shops (lowest price an NPC asks for one potion or rune; no thrown weapons since 2026-10-20). Regenerate:',
        '--     python3 -I server/tools/gen_supply_prices.py <server>/data',
        '-- [server item id] = gold per unit',
        'return {',
    ]
    ids = sorted(prices)
    for i in range(0, len(ids), 8):
        lines.append('\t' + ' '.join('[%d] = %d,' % (k, prices[k]) for k in ids[i:i + 8]))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 1
    data_dir = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) == 3 else os.path.join(data_dir, 'scripts', 'chaos', 'hunt_supplies.lua')
    prices = collect(data_dir)
    if not prices:
        print('no supply prices found under', data_dir)
        return 1
    with open(out, 'w', encoding='utf-8') as f:
        f.write(render(prices))
    print(f'{out}: {len(prices)} supplies')
    return 0


if __name__ == '__main__':
    sys.exit(main())
