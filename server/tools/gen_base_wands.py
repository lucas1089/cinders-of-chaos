#!/usr/bin/env python3
"""Write data/lib/chaos_base_wands.lua: the weapons.xml damage of the stock wands and rods (O353).

usage: python3 -I server/tools/gen_base_wands.py [--check]

The engine does not give weapons.xml numbers to Lua, so the item tooltip (item_tooltip.lua, ChaosWeaponDps.wands) reads
the stock wands' and rods' min and max from this table. Source: data/items/base_weapons.csv (kind wand or rod, columns
wmin and wmax; re-run tools/survey_base_weapons.py on an installed server when a base weapon changes). --check fails
when the committed file differs from what this script writes.
O472: the CSV holds the damage before the weapon growth; the step tools/patch_stock_weapon_growth.py sets the weapons.xml damage of a
wand or rod of a level above 100 to the CSV's times a(level), so this table has the grown numbers.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import weapon_growth as WG  # noqa: E402  (O472: the stock wands grow with the level, patch_stock_weapon_growth.py)
SERVER = os.path.dirname(HERE)
SRC = os.path.join(SERVER, 'data', 'items', 'base_weapons.csv')
OUT = os.path.join(SERVER, 'data', 'lib', 'chaos_base_wands.lua')

HEAD = """-- The stock wands and rods: their weapons.xml damage (O353), for the item tooltip's Attack and Estimated DPS rows
-- (data/scripts/chaos/item_tooltip.lua, weapon_dps_core.lua collectWands). Generated by server/tools/gen_base_wands.py
-- from data/items/base_weapons.csv; do not edit by hand. [server id] = {stats = {wandMin, wandMax}}.
"""


def rows(path=SRC):
    out = []
    with open(path, newline='', encoding='utf-8') as f:
        for r in csv.DictReader(f):
            if r.get('kind') not in ('wand', 'rod'):
                continue
            try:
                iid, lo, hi = int(r['id']), int(r['wmin'] or 0), int(r['wmax'] or 0)
                level = int(r.get('level') or 0)
            except (KeyError, ValueError):
                continue
            if level > 100:
                lo, hi = WG.grown(lo, level), WG.grown(hi, level)
            if hi > 0:
                out.append((iid, min(lo, hi), max(lo, hi)))
    return sorted(out)


def render(items):
    lines = [HEAD.rstrip('\n'), 'return {']
    for iid, lo, hi in items:
        lines.append('\t[%d] = {stats = {wandMin = %d, wandMax = %d}},' % (iid, lo, hi))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main(argv):
    items = rows()
    text = render(items)
    if '--check' in argv:
        try:
            with open(OUT, encoding='utf-8') as f:
                old = f.read()
        except OSError:
            old = None
        if old != text:
            print('chaos_base_wands.lua is out of date: python3 -I server/tools/gen_base_wands.py')
            return 1
        print('base wands: ok (%d)' % len(items))
        return 0
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s (%d wands and rods)' % (OUT, len(items)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
