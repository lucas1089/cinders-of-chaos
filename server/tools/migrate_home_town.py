#!/usr/bin/env python3
"""One-shot, optional: move existing characters' home town to the main city (server/README.md "Main city").

usage: python3 -I server/tools/migrate_home_town.py [--from IDS] [--to ID] [--max-level N] [--out FILE]

New characters already live in the main city (newplayer_config.lua homeTown: the game moves a brand-new character
there at its first login). Characters made before keep their town. This tool writes the SQL that moves them too; it
never connects to the database. Run the SQL with the game server STOPPED (a running server writes each online
character's town back at its next save) and after a backup (server/tools/backup.sh):
    python3 -I server/tools/migrate_home_town.py --from 1 > home.sql && mysql chaos < home.sql

  --from IDS      comma-separated town ids to move from (default: every town but the target)
  --to ID         the main city (default: homeTown.id of server/data/scripts/chaos/newplayer_config.lua)
  --max-level N   only characters of level N or lower (default: every level)
  --out FILE      write the SQL to FILE instead of standard output

What changes: `players`.`town_id` (the temple, the respawn after death, the Town Portal and the temple scroll). What
stays: the position (a character logs in where it logged out), houses, and the depots: depots are per town, so the
items in another town's depot stay there (the stash window shows every depot). Idempotent: a second run changes no row.
Rollback: the backup, or the same tool with --from and --to swapped (it cannot tell who lived where before).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG = os.path.join(os.path.dirname(HERE), 'data', 'scripts', 'chaos', 'newplayer_config.lua')


class UsageError(Exception):
    pass


def configured_home(path=CONFIG):
    """homeTown.id of newplayer_config.lua, or None"""
    try:
        with open(path, encoding='utf-8') as f:
            text = f.read()
    except OSError:
        return None
    m = re.search(r'^\s*homeTown\s*=\s*\{\s*id\s*=\s*(\d+)', text, re.M)
    return int(m.group(1)) if m else None


def ids(text):
    out = []
    for part in text.split(','):
        part = part.strip()
        if not part.isdigit() or int(part) <= 0:
            raise UsageError('not a town id: %r' % part)
        if int(part) not in out:
            out.append(int(part))
    return out


def build_sql(to_id, from_ids=None, max_level=None):
    """the SQL text (pure; tested by migrate_home_town_test.py)"""
    if not isinstance(to_id, int) or to_id <= 0:
        raise UsageError('no target town (--to, or homeTown.id in newplayer_config.lua)')
    if from_ids is not None:
        from_ids = [i for i in from_ids if i != to_id]
        if not from_ids:
            raise UsageError('--from holds only the target town: nothing to move')
    where = ['`town_id` <> %d' % to_id]
    if from_ids is not None:
        where.append('`town_id` IN (%s)' % ', '.join(str(i) for i in from_ids))
    if max_level is not None:
        if max_level <= 0:
            raise UsageError('--max-level must be 1 or more')
        where.append('`level` <= %d' % max_level)
    cond = ' AND '.join(where)
    return ('-- Cinders of Chaos: move existing characters to the main city (town %d). GENERATED by\n'
            '-- server/tools/migrate_home_town.py. Run with the game server stopped, after a backup.\n'
            'START TRANSACTION;\n'
            'SELECT `town_id`, COUNT(*) AS `characters` FROM `players` WHERE %s GROUP BY `town_id`;\n'
            'UPDATE `players` SET `town_id` = %d WHERE %s;\n'
            'COMMIT;\n') % (to_id, cond, to_id, cond)


def main(argv):
    opts = {'--from': None, '--to': None, '--max-level': None, '--out': None}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a in ('-h', '--help'):
            print(__doc__)
            return 0
        if a not in opts or i + 1 >= len(argv):
            raise UsageError('unknown or incomplete option: %s' % a)
        opts[a] = argv[i + 1]
        i += 2
    to_id = configured_home() if opts['--to'] is None else ids(opts['--to'])[0]
    from_ids = None if opts['--from'] is None else ids(opts['--from'])
    max_level = None
    if opts['--max-level'] is not None:
        if not opts['--max-level'].isdigit():
            raise UsageError('--max-level takes a number')
        max_level = int(opts['--max-level'])
    sql = build_sql(to_id, from_ids, max_level)
    if opts['--out']:
        with open(opts['--out'], 'w', encoding='utf-8') as f:
            f.write(sql)
        sys.stderr.write('migrate_home_town: wrote %s\n' % opts['--out'])
    else:
        sys.stdout.write(sql)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main(sys.argv[1:]))
    except UsageError as e:
        sys.stderr.write('migrate_home_town: %s\n' % e)
        sys.exit(2)
