#!/usr/bin/env python3
"""The wings, head accessories and capes of client pair 33 for the server: their ids, names and store prices.

usage (from the repository root or server/): python3 -I server/tools/gen_pack33_cosmetics.py [--check]

Reads the things files of client/tools/sprites/gen_pack33.py (art_import/pack33_wings.csv, pack33_heads.csv,
pack33_capes.csv: the kept pieces in id order, the client look in the extra's id=) and writes
  server/data/lib/chaos_pack33_cosmetics.lua   M.wings, M.heads, M.capes: one line per piece
                                               {key, id, look, name, element, cost}
  server/data/XML/chaos_auras_pack33.csv       the heads and capes as auras (aura_id, client_id, name), the rows
                                               install_auras.py adds while ChaosPack33.PAIR33 is on
--check compares both with the committed files (CI) and exits 1 when they differ.

Ids follow the existing ones: wings.xml 30.. (ours end at 29), auras.xml 33.. (ours end at 32), heads first, then
capes; the order is the client's look order, so a piece keeps its id as long as the things files keep their rows.
The heads and capes are auras (owner 2026-10-21: no engine change): a player wears one aura, head accessory or cape at
a time.
Prices (coins; server/README.md "Pair 33 cosmetics"), by the piece's drawn size like the store's other cosmetics
(wings 200-350, auras 150-300):
  wings: 3x3 250, larger (4x3, 4x4) 300           heads: 2x2 or smaller 150, larger 200
  capes: 2x2 or smaller 200, larger 250
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SERVER = os.path.dirname(HERE)
ROOT = os.path.dirname(SERVER)
ART = os.path.join(ROOT, 'client', 'tools', 'sprites', 'art_import')
LUA = os.path.join(SERVER, 'data', 'lib', 'chaos_pack33_cosmetics.lua')
CSV = os.path.join(SERVER, 'data', 'XML', 'chaos_auras_pack33.csv')

FIRST_WINGS = 30
FIRST_AURA = 33
MAX_ID = 255
# slug -> (key prefix, suffix cut from the pack id for the key)
KINDS = {'wings': ('wings_', '_wings'), 'heads': ('head_', ''), 'capes': ('cape_', '')}


def cost(slug, w, h):
    big = max(w, h) > (3 if slug == 'wings' else 2)
    return {'wings': (250, 300), 'heads': (150, 200), 'capes': (200, 250)}[slug][1 if big else 0]


def read(slug):
    out = []
    prefix, cut = KINDS[slug]
    for r in csv.DictReader(open(os.path.join(ART, 'pack33_%s.csv' % slug), newline='', encoding='utf-8')):
        eid = r['key'].split('__', 1)[1]
        stem = eid[:-len(cut)] if cut and eid.endswith(cut) else eid
        look = int(re.match(r'id=(\d+)\|', r['extra']).group(1))
        element = re.search(r'element=(\w+)', r['extra']).group(1)
        name = r['name']
        if not re.match(r"^[A-Za-z][A-Za-z' -]*$", name):
            sys.exit('%s: odd name %r' % (eid, name))
        out.append({'key': prefix + stem, 'look': look, 'name': name, 'element': element,
                    'cost': cost(slug, int(r['w']), int(r['h']))})
    return out


def build():
    wings, heads, capes = read('wings'), read('heads'), read('capes')
    for i, w in enumerate(wings):
        w['id'] = FIRST_WINGS + i
    for i, a in enumerate(heads + capes):
        a['id'] = FIRST_AURA + i
    ids = [w['id'] for w in wings] + [a['id'] for a in heads + capes]
    if max(ids) > MAX_ID:
        sys.exit('ids past %d' % MAX_ID)
    keys = [x['key'] for x in wings + heads + capes]
    if len(set(keys)) != len(keys) or any(len(k) > 40 for k in keys):
        sys.exit('keys must be unique and 40 characters at most')
    looks = [x['look'] for x in wings + heads + capes]
    if looks != list(range(looks[0], looks[0] + len(looks))):
        sys.exit('the looks are not contiguous in wings, heads, capes order')

    def lines(rows):
        return ',\n'.join('\t{key = "%s", id = %d, look = %d, name = "%s", element = "%s", cost = %d}' % (
            x['key'], x['id'], x['look'], x['name'], x['element'], x['cost']) for x in rows)
    lua = ('-- Generated by server/tools/gen_pack33_cosmetics.py from client/tools/sprites/art_import/pack33_{wings,heads,'
           'capes}.csv.\n-- Do not edit: change gen_pack33.py (what is kept) or the prices in the generator, then run it '
           'again.\n-- Client pair 33 looks %d..%d. Wings: wings.xml ids %d..%d. Heads and capes: auras.xml ids %d..%d '
           '(chaos_auras_pack33.csv).\n-- Read by data/lib/chaos_pack33.lua (the PAIR33 switch, the store, the '
           'exclusives) and server/tools/install_outfits.py.\n'
           'local M = {}\n\nM.wings = {\n%s\n}\n\nM.heads = {\n%s\n}\n\nM.capes = {\n%s\n}\n\nreturn M\n') % (
        looks[0], looks[-1], wings[0]['id'], wings[-1]['id'], heads[0]['id'], capes[-1]['id'],
        lines(wings), lines(heads), lines(capes))
    rows = ''.join('%d,%d,%s\n' % (a['id'], a['look'], a['name']) for a in heads + capes)
    return lua, 'aura_id,client_id,name\n' + rows, (wings, heads, capes)


def main(argv):
    lua, auras, (wings, heads, capes) = build()
    if '--check' in argv:
        bad = 0
        for path, text in ((LUA, lua), (CSV, auras)):
            cur = open(path, encoding='utf-8').read() if os.path.isfile(path) else None
            if cur != text:
                print('DIFF %s (run server/tools/gen_pack33_cosmetics.py)' % os.path.relpath(path, ROOT))
                bad += 1
        print('gen_pack33_cosmetics --check: %s' % ('OK' if not bad else '%d files differ' % bad))
        return 1 if bad else 0
    open(LUA, 'w', encoding='utf-8').write(lua)
    open(CSV, 'w', encoding='utf-8').write(auras)
    print('wrote %s (%d wings, %d heads, %d capes) and %s' % (os.path.relpath(LUA, ROOT), len(wings), len(heads),
                                                             len(capes), os.path.relpath(CSV, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
