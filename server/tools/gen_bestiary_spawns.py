#!/usr/bin/env python3
"""Bestiary spawn data (data/scripts/chaos/bestiary_spawns.lua) from the map that is really loaded.

usage: python3 -I gen_bestiary_spawns.py DATA_DIR [OUT_FILE] [--spawn PATH] [--config PATH]

Reads the spawn file of the loaded map (DATA_DIR/world/<mapName>-spawn.xml, mapName from config.lua, default
DATA_DIR/../config.lua, or --spawn PATH) and writes OUT_FILE (default: data/scripts/chaos/bestiary_spawns.lua of this
repo) as a plain Lua table keyed by the lower-case monster name:

    ["dragon"] = {spawns = 412, areas = {{32456, 31612, 9, 88}, ...}},

spawns = spawn entries on the map (the bestiary needs fewer kills for monsters with only a few, and kill tasks are only
offered for monsters that spawn); areas = up to AREAS clusters {x, y, z, entries}: the spawn entries are grouped in
CELL x CELL squares per floor and the busiest squares are kept, at their mean position. bestiary.lua names each one by
the nearest temple of the running server (Game.getTowns), so no town names are written here.

Rerun it after any change to the spawn file (for example after tools/late_game.py), together with gen_bounty_pool.py.
The output is sorted and carries no date. Names the project's name check would reject are left out (the same rule as
gen_bounty_pool.py, whose spawn parsing this reuses).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_bounty_pool as pool  # noqa: E402  (map_name, attr, num, read, DENY)

DEFAULT_OUT = os.path.join(HERE, '..', 'data', 'scripts', 'chaos', 'bestiary_spawns.lua')
CELL = 160
AREAS = 3


def parse(text):
    """{lower name: {'count': n, 'cells': {(cx, cy, z): [n, sumx, sumy]}}} from a spawn file."""
    out = {}
    for block in re.finditer(r'<spawn\s([^>]*)>(.*?)</spawn>', text, re.S):
        head, body = block.group(1), block.group(2)
        cx, cy, cz = pool.num(pool.attr(head, 'centerx')), pool.num(pool.attr(head, 'centery')), pool.num(pool.attr(head, 'centerz'))
        for m in re.finditer(r'<monster\s[^>]*?/?>', body):
            tag = m.group(0)
            name = pool.attr(tag, 'name')
            if not name:
                continue
            x = cx + pool.num(pool.attr(tag, 'x'))
            y = cy + pool.num(pool.attr(tag, 'y'))
            z = pool.num(pool.attr(tag, 'z'), cz)
            e = out.setdefault(name.lower(), {'count': 0, 'cells': {}})
            e['count'] += 1
            c = e['cells'].setdefault((x // CELL, y // CELL, z), [0, 0, 0])
            c[0] += 1
            c[1] += x
            c[2] += y
    return out


def render(spawns):
    out = [
        '-- Bestiary spawn data (bestiary.lua). GENERATED by server/tools/gen_bestiary_spawns.py: do not edit by hand,',
        '-- rerun the tool after changing spawns (e.g. tools/late_game.py), as gen_bounty_pool.py.',
        '-- Source: world/<mapName>-spawn.xml. spawns = spawn entries on the map; areas = the busiest %dx%d squares per floor' % (CELL, CELL),
        '-- as {x, y, z, entries} at their mean position (bestiary.lua names them after the nearest temple).',
        '-- %d monster names.' % len(spawns),
        '',
        'return {',
    ]
    for key in sorted(spawns):
        e = spawns[key]
        cells = sorted(e['cells'].items(), key=lambda kv: (-kv[1][0], kv[0]))[:AREAS]
        areas = ', '.join('{%d, %d, %d, %d}' % (round(c[1] / c[0]), round(c[2] / c[0]), k[2], c[0]) for k, c in cells)
        out.append('\t[%s] = {spawns = %d, areas = {%s}},' % (pool.lua_string(key), e['count'], areas))
    out += ['}', '']
    return '\n'.join(out)


def main():
    argv = sys.argv[1:]
    opts = {}
    for k in ('--spawn', '--config'):
        if k in argv:
            i = argv.index(k)
            opts[k] = argv[i + 1]
            del argv[i:i + 2]
    if not argv or len(argv) > 2:
        print(__doc__)
        return 1
    data_dir = argv[0]
    out_path = argv[1] if len(argv) == 2 else DEFAULT_OUT
    spawn_path = opts.get('--spawn')
    if not spawn_path:
        cfg_path = opts.get('--config', os.path.join(data_dir, '..', 'config.lua'))
        name = pool.map_name(pool.read(cfg_path))
        if not name:
            print(f'{cfg_path}: mapName not found, pass --spawn')
            return 1
        spawn_path = os.path.join(data_dir, 'world', name + '-spawn.xml')
    spawns = parse(pool.read(spawn_path))
    dropped = [k for k in spawns if pool.DENY and pool.DENY.search(k)]
    for k in dropped:
        del spawns[k]
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render(spawns))
    print(f'{out_path}: {len(spawns)} monster names ({len(dropped)} left out by the name check)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
