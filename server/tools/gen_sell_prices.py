#!/usr/bin/env python3
"""Build the NPC sell-price table the store's Auto Seller uses (data/scripts/chaos/sell_prices.lua).

usage: python3 -I gen_sell_prices.py DATA_DIR [OUT_FILE]

Reads every NPC of the base server and collects what NPCs pay for an item:
  - data/npc/*.xml           <parameter key="shop_sellable" value="name,id,price[,subtype];..."/>
  - data/npc/scripts/*.lua   shopModule:addSellableItem({...}, id, price, ...)
                             {name = '...', id = 1234, ..., sell = 75} tables
The highest price any NPC pays wins. Entries with a subtype (fluids) and prices <= 0 are skipped.
OUT_FILE defaults to DATA_DIR/scripts/chaos/sell_prices.lua. The output is a plain Lua table
({[server item id] = gold}) and is deterministic (sorted by id), so it can be kept in the repo.
"""
import glob, os, re, sys

XML_PARAM = re.compile(r'key\s*=\s*"shop_sellable"\s+value\s*=\s*"([^"]*)"', re.S)
LUA_ADD = re.compile(r'addSellableItem\s*\(\s*(?:\{[^}]*\}|nil|"[^"]*"|\'[^\']*\')\s*,\s*(\d+)\s*,\s*(\d+)')
LUA_TABLE = re.compile(r'\{[^{}]*?\bid\s*=\s*(\d+)[^{}]*?\bsell\s*=\s*(\d+)[^{}]*?\}')


def read(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return f.read()


def collect(data_dir):
    prices = {}

    def put(item_id, price):
        if price > 0 and item_id > 0 and price > prices.get(item_id, 0):
            prices[item_id] = price

    for path in sorted(glob.glob(os.path.join(data_dir, 'npc', '*.xml'))):
        for value in XML_PARAM.findall(read(path)):
            for entry in value.split(';'):
                parts = [p.strip() for p in entry.split(',')]
                if len(parts) < 3 or not parts[1].isdigit() or not parts[2].isdigit():
                    continue
                if len(parts) >= 4 and parts[3] not in ('', '0'):
                    continue  # fluid subtype
                put(int(parts[1]), int(parts[2]))
    for path in sorted(glob.glob(os.path.join(data_dir, 'npc', 'scripts', '*.lua'))):
        text = read(path)
        for item_id, price in LUA_ADD.findall(text):
            put(int(item_id), int(price))
        for item_id, price in LUA_TABLE.findall(text):
            put(int(item_id), int(price))
    return prices


def render(prices):
    lines = [
        '-- NPC sell prices for the store\'s Auto Seller (autosell.lua). GENERATED by server/tools/gen_sell_prices.py',
        '-- from the base server\'s NPC shops (highest price any NPC pays). Regenerate after NPC changes:',
        '--     python3 -I server/tools/gen_sell_prices.py <server>/data',
        '-- [server item id] = gold per item',
        'return {',
    ]
    ids = sorted(prices)
    for i in range(0, len(ids), 8):
        lines.append('\t' + ' '.join('[%d] = %d,' % (k, prices[k]) for k in ids[i:i + 8]))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 1
    data_dir = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) == 3 else os.path.join(data_dir, 'scripts', 'chaos', 'sell_prices.lua')
    prices = collect(data_dir)
    if not prices:
        print('no NPC sell prices found under', data_dir)
        return 1
    with open(out, 'w', encoding='utf-8') as f:
        f.write(render(prices))
    print(f'{out}: {len(prices)} items')
    return 0


if __name__ == '__main__':
    sys.exit(main())
