-- Regenerates client/overlay/modules/game_spellranks/awakened_data.lua (O686 phase 7): the awakened name (English and pt-BR), the role and the
-- signature parts of every attack and heal spell, the slot costs and the +10%, for the Awakening part of the Upgrades tab and the Spellbook
-- row names. Source: data/spells/awakened.csv (tools/gen_awakened.py writes it), spell_awakening_config.lua, spell_ranks_config.lua.
-- The sentence of a signature is made on the client from its parts (awakelogic.lua A.sentences); its English templates have their pt-BR in
-- client_chaos_locale/pt_br.lua (--check also fails when one is missing).
-- Run from the server/ folder:
--   luajit tools/gen_awakened_data.lua            write the client file
--   luajit tools/gen_awakened_data.lua --check    exit 1 when the client file differs from what the data gives, or a template has no pt-BR (CI)
--   lua5.3 works the same; the output is byte-identical under both (CI checks both).
-- No clock, no random, no pairs() order. Pure helpers are exported for tests: set AWAKENED_GEN_NO_MAIN = true before dofile().

local Gen = {}
local floor = math.floor

local OUT_DEFAULT = "../client/overlay/modules/game_spellranks/awakened_data.lua"
local PT_BR = "../client/overlay/modules/client_chaos_locale/pt_br.lua"
local CLIENT_LOGIC = "../client/overlay/modules/game_spellranks/awakelogic.lua"
Gen.SOURCES = {"data/spells/awakened.csv", "data/scripts/chaos/spell_awakening_core.lua", "data/scripts/chaos/spell_awakening_config.lua",
	"data/scripts/chaos/spell_ranks_config.lua"}

dofile("data/scripts/chaos/spell_awakening_core.lua")
local A = ChaosSpellAwakeningCore

function Gen.num(v)
	if v == floor(v) then
		return string.format("%d", v)
	end
	return string.format("%g", v)
end

function Gen.q(s)
	s = tostring(s):gsub("[%c\"\\]", function(c)
		if c == "\"" then
			return "\\\""
		elseif c == "\\" then
			return "\\\\"
		elseif c == "\n" then
			return "\\n"
		end
		return string.format("\\%03d", c:byte())
	end)
	return "\"" .. s .. "\""
end

local function readAll(path)
	local f = assert(io.open(path, "r"))
	local s = f:read("*a")
	f:close()
	return s
end

-- the parts of a spec as a Lua literal: {{"PULSE", {minHit = 3, ...}}, ...}, keys in the order of A.numbers' sorted names
local function partsLiteral(spec)
	local out = {}
	for _, p in ipairs(spec.parts) do
		local keys = {}
		for k in pairs(p.n) do
			keys[#keys + 1] = k
		end
		table.sort(keys)
		local items = {}
		for _, k in ipairs(keys) do
			items[#items + 1] = k .. " = " .. Gen.num(p.n[k])
		end
		out[#out + 1] = "{" .. Gen.q(p.kind) .. ", {" .. table.concat(items, ", ") .. "}}"
	end
	return "{" .. table.concat(out, ", ") .. "}"
end

function Gen.build(rows, cfg, rcfg)
	local ids = {}
	for id in pairs(rows) do
		ids[#ids + 1] = id
	end
	table.sort(ids)
	local o = {}
	local function add(s)
		o[#o + 1] = s
	end
	add("-- Generated by server/tools/gen_awakened_data.lua from server/data/spells/awakened.csv (O686 phase 7): the awakened name and the signature parts of")
	add("-- every attack and heal spell, the slot costs and the bonus. Do not edit: cd server && luajit tools/gen_awakened_data.lua (CI checks it with --check, under")
	add("-- LuaJIT and Lua 5.3). The sentence of a signature is made from its parts by awakelogic.lua; the English templates have their pt-BR in pt_br.lua.")
	add("ChaosAwakenedData = {")
	add("  v = 1,")
	add("  rank = " .. Gen.num(rcfg.maxRank) .. ",")
	add("  maxSlots = " .. Gen.num(cfg.maxSlots) .. ",")
	add("  bonus = " .. Gen.num(cfg.bonus) .. ",")
	local slots = {}
	for _, s in ipairs(cfg.slots) do
		slots[#slots + 1] = string.format("{%d, %d, %d}", s.waystone, s.rift, s.pinnacle)
	end
	add("  slots = {" .. table.concat(slots, ", ") .. "},")
	add("  spells = {")
	for _, id in ipairs(ids) do
		local s = rows[id]
		add(string.format("    [%d] = {en = %s, pt = %s, heal = %s, parts = %s},", id, Gen.q(s.nameEn), Gen.q(s.namePt), tostring(s.heal),
			partsLiteral(s)))
	end
	add("  },")
	add("}")
	return table.concat(o, "\n") .. "\n"
end

-- the English templates of awakelogic.lua A.TEMPLATES, read from its source (one copy: the client file)
function Gen.templates()
	local text = readAll(CLIENT_LOGIC)
	local block = text:match("A%.TEMPLATES = {(.-)\n}")
	local out = {}
	for key, value in (block or ""):gmatch("(%w+) = '([^']*)'") do
		out[#out + 1] = {key = key, en = value}
	end
	return out
end

function Gen.loadPt()
	local text = readAll(PT_BR)
	local pt = {}
	for key, value in text:gmatch('%["([^\n]-)"%]%s*=%s*"([^\n]*)",') do
		pt[key] = value
	end
	return pt
end

function Gen.ptProblems(templates, pt)
	local bad = {}
	for _, t in ipairs(templates) do
		local v = pt[t.en]
		if v == nil or v == "" then
			bad[#bad + 1] = "pt_br.lua has no entry for " .. Gen.q(t.en)
		else
			local function formats(s)
				local n = {}
				for f in s:gmatch("%%[sd]") do
					n[#n + 1] = f
				end
				return table.concat(n)
			end
			if formats(v) ~= formats(t.en) then
				bad[#bad + 1] = "pt_br.lua " .. Gen.q(t.en) .. " has other % formats"
			end
		end
	end
	return bad
end

function Gen.run(args)
	local rows = assert(A.parse(readAll("data/spells/awakened.csv")))
	local cfg = dofile("data/scripts/chaos/spell_awakening_config.lua")
	local rcfg = dofile("data/scripts/chaos/spell_ranks_config.lua")
	local out = Gen.build(rows, cfg, rcfg)
	local path = OUT_DEFAULT
	local check = false
	for _, a in ipairs(args) do
		if a == "--check" then
			check = true
		end
	end
	if check then
		local templates = Gen.templates()
		local bad = Gen.ptProblems(templates, Gen.loadPt())
		if #templates < 10 then
			bad[#bad + 1] = "awakelogic.lua A.TEMPLATES was not read"
		end
		local f = io.open(path, "r")
		local have = f and f:read("*a") or nil
		if f then
			f:close()
		end
		if have ~= out then
			bad[#bad + 1] = path .. " is not what the data gives: run luajit tools/gen_awakened_data.lua"
		end
		for _, b in ipairs(bad) do
			print("FAIL " .. b)
		end
		if #bad > 0 then
			return 1
		end
		print("gen_awakened_data: ok (" .. #templates .. " templates with a pt-BR entry)")
		return 0
	end
	local f = assert(io.open(path, "w"))
	f:write(out)
	f:close()
	print("wrote " .. path)
	return 0
end

if not AWAKENED_GEN_NO_MAIN then
	os.exit(Gen.run(arg or {}))
end

return Gen
