-- Regenerates client/overlay/modules/game_spellranks/forms_data.lua (O686 phase 4): the Forms of every attack and heal spell for the client's
-- Form picker (phase 5): per kind its tier, situation, utility and plain sentence (numbers from spell_forms_core.lua), per spell its name,
-- element and the two Form I and two Form II (kind and English name, a sentence of its own only when a forms.csv override changes it), and
-- the pick rules of spell_ranks_config.lua `forms`. The pt-BR of every name and sentence is in client_chaos_locale/pt_br.lua (run-time keys:
-- the client gives the English text to tr()); --check also fails when one is missing or a name differs from forms.csv `name_pt`.
-- Run from the server/ folder:
--   luajit tools/gen_forms_data.lua            write the client file
--   luajit tools/gen_forms_data.lua --pt       print the pt_br.lua lines of every text the client file needs
--   luajit tools/gen_forms_data.lua --check    exit 1 when the client file differs from what the data gives, or a pt-BR text is missing (CI)
--   lua5.3 works the same; the output is byte-identical under both (CI checks both).
-- No clock, no random, no pairs() order. Pure helpers are exported for tests: set FORMS_GEN_NO_MAIN = true before dofile().

local Gen = {}
local floor = math.floor

local OUT_DEFAULT = "../client/overlay/modules/game_spellranks/forms_data.lua"
local PT_BR = "../client/overlay/modules/client_chaos_locale/pt_br.lua"
Gen.SOURCES = {"data/scripts/chaos/spell_forms_core.lua", "data/spells/forms.csv", "tools/forms_text_config.lua",
	"data/scripts/chaos/spell_ranks_config.lua"}

dofile("data/scripts/chaos/spell_forms_core.lua")
local F = ChaosSpellFormsCore

-- a number as a short plain text: 35 -> "35", 3.5 -> "3.5"
function Gen.num(v)
	if v == floor(v) then
		return string.format("%d", v)
	end
	return string.format("%g", v)
end

-- a Lua string literal: double quotes, backslash and control characters escaped, UTF-8 left as it is
function Gen.q(s)
	s = tostring(s):gsub("[%c\"\\]", function(c)
		if c == "\"" then
			return "\\\""
		elseif c == "\\" then
			return "\\\\"
		elseif c == "\n" then
			return "\\n"
		end
		return string.format("\\%03d", c:byte())
	end)
	return "\"" .. s .. "\""
end

-- the sentence of a kind with its numbers (a forms.csv override applied); `comma`: the pt-BR decimal comma
function Gen.text(template, base, over, comma)
	local p = F.params(base, over)
	local function fmt(v)
		local t = Gen.num(v)
		if comma then
			t = t:gsub("%.", ",")
		end
		return t
	end
	local out = template:gsub("{(%w+)}", function(key)
		if key == "sec" then
			return fmt((p.ms or 0) / 1000)
		elseif key == "ticksSec" then
			return fmt((p.ticks or 0) * (p.every or 1000) / 1000)
		end
		local v = p[key]
		if v == nil then
			error("the sentence of " .. base .. " names {" .. key .. "}, which is no number of the kind")
		end
		return fmt(v)
	end)
	return out
end

function Gen.textPt(template, base, over)
	return Gen.text(template, base, over, true)
end

local function readFile(path)
	local f = assert(io.open(path, "r"))
	local text = f:read("*a")
	f:close()
	return text
end

-- forms.csv rows (the lib parser): {[spell id] = {name, heal, element, [1] = {row, row}, [2] = {row, row}}}
function Gen.rows(path)
	dofile("data/lib/chaos_spell_forms.lua")
	local rows, err = ChaosSpellForms.parse(readFile(path or "data/spells/forms.csv"))
	assert(rows, err)
	return rows
end

-- the kinds in a fixed order
function Gen.kindOrder()
	local out = {}
	for _, list in ipairs({F.kinds1, F.kinds2, F.heal1, F.heal2}) do
		for _, k in ipairs(list) do
			out[#out + 1] = k
		end
	end
	return out
end

-- the whole file text, and the list of English texts the client will give to tr() (names and sentences)
function Gen.build(rows, all, cfg)
	local texts, ptTexts = all.en, all.pt
	local lines = {}
	local function add(s)
		lines[#lines + 1] = s
	end
	local needed, seen = {}, {}
	local function need(en, pt)
		if not seen[en] then
			seen[en] = true
			needed[#needed + 1] = {en = en, pt = pt}
		end
	end
	add("-- GENERATED by server/tools/gen_forms_data.lua from server/data/spells/forms.csv, spell_forms_core.lua and tools/forms_text_config.lua.")
	add("-- Do not edit: cd server && luajit tools/gen_forms_data.lua (CI checks it with --check, under LuaJIT and Lua 5.3).")
	add("-- Names and sentences are English: the client gives them to tr() (pt-BR in client_chaos_locale/pt_br.lua, run-time keys).")
	add("-- Format: docs/SPELL_UPGRADES.md section 2; the pick rules are spell_ranks_config.lua `forms`.")
	add("ChaosFormsData = {")
	local f = cfg.forms
	add(string.format("\tpick = {rank1 = %d, rank2 = %d, minPrice = %d, perLevel = %d, freeSeconds = %d},", f.rank1, f.rank2, f.minPrice,
		f.perLevel, f.freeSeconds))
	add("\tkinds = {")
	for _, k in ipairs(Gen.kindOrder()) do
		local tier = (F.set1[k] or F.setHeal1[k]) and 1 or 2
		local heal = (F.setHeal1[k] or F.setHeal2[k]) and "true" or "false"
		local text = Gen.text(assert(texts[k], "no sentence for " .. k), k, nil)
		need(text, Gen.textPt(assert(ptTexts[k], "no pt-BR sentence for " .. k), k, nil))
		local util = F.utility[k] and (", utility = " .. Gen.q(F.utility[k])) or ""
		if F.utility[k] then
			need(F.utility[k], all.ptUtility[k])
		end
		add(string.format("\t\t%s = {tier = %d, heal = %s, scope = %s, situation = %s, text = %s%s},", k, tier, heal,
			Gen.q(F.scope[k]), Gen.q(F.situation[k]), Gen.q(text), util))
	end
	add("\t},")
	add("\tspells = {")
	local ids = {}
	for id in pairs(rows) do
		ids[#ids + 1] = id
	end
	table.sort(ids)
	for _, id in ipairs(ids) do
		local s = rows[id]
		local parts = {}
		for tier = 1, 2 do
			local picks = {}
			for pick = 1, 2 do
				local sp = s[tier][pick]
				local en, pt = sp.nameEn, sp.namePt
				need(en, pt)
				local entry = string.format("{%s, %s", Gen.q(sp.row.kind), Gen.q(en))
				-- a sentence of its own when an override changes the kind's
				if next(sp.over) then
					local own = Gen.text(texts[sp.kind], sp.kind, sp.over)
					local plain = Gen.text(texts[sp.kind], sp.kind, nil)
					if own ~= plain then
						need(own, Gen.textPt(ptTexts[sp.kind], sp.kind, sp.over))
						entry = entry .. ", " .. Gen.q(own)
					end
				end
				picks[#picks + 1] = entry .. "}"
			end
			parts[#parts + 1] = "{" .. table.concat(picks, ", ") .. "}"
		end
		add(string.format("\t\t[%d] = {name = %s, heal = %s%s, forms = {%s}},", id, Gen.q(s.name), s.heal and "true" or "false",
			s.element and (", element = " .. Gen.q(s.element)) or "", table.concat(parts, ", ")))
	end
	add("\t},")
	add("}")
	return table.concat(lines, "\n") .. "\n", needed
end

-- `--pt` prints the pt_br.lua lines of every text the client file needs (to paste under the game_spellranks run-time keys)
function Gen.ptLines(needed)
	local out = {}
	for _, n in ipairs(needed) do
		out[#out + 1] = string.format("  [%s] = %s,", Gen.q(n.en), Gen.q(n.pt or "?"))
	end
	return out
end

-- the pt-BR table
function Gen.loadPt(path)
	ChaosLocaleStrings = nil
	dofile(path or PT_BR)
	return ChaosLocaleStrings["pt-BR"]
end

-- problems of the pt-BR table against the needed texts: a missing entry, a name that differs from forms.csv
function Gen.ptProblems(needed, pt)
	local bad = {}
	for _, n in ipairs(needed) do
		local v = pt[n.en]
		if v == nil or v == "" then
			bad[#bad + 1] = "pt_br.lua has no entry for " .. Gen.q(n.en)
		elseif n.pt and v ~= n.pt then
			bad[#bad + 1] = "pt_br.lua " .. Gen.q(n.en) .. " is " .. Gen.q(v) .. ", forms.csv says " .. Gen.q(n.pt)
		end
	end
	return bad
end

function Gen.run(args)
	local rows = Gen.rows()
	local texts = dofile("tools/forms_text_config.lua")
	local cfg = dofile("data/scripts/chaos/spell_ranks_config.lua")
	local out, needed = Gen.build(rows, texts, cfg)
	local path = OUT_DEFAULT
	local check, write = false, true
	for _, a in ipairs(args) do
		if a == "--check" then
			check, write = true, false
		elseif a == "--pt" then
			for _, l in ipairs(Gen.ptLines(needed)) do
				print(l)
			end
			return 0
		end
	end
	if check then
		local bad = Gen.ptProblems(needed, Gen.loadPt())
		local f = io.open(path, "r")
		local have = f and f:read("*a") or nil
		if f then
			f:close()
		end
		if have ~= out then
			bad[#bad + 1] = path .. " is not what the data gives: run luajit tools/gen_forms_data.lua"
		end
		for _, b in ipairs(bad) do
			print("FAIL " .. b)
		end
		if #bad > 0 then
			return 1
		end
		print("gen_forms_data: ok (" .. #needed .. " texts with a pt-BR entry)")
		return 0
	end
	if write then
		local f = assert(io.open(path, "w"))
		f:write(out)
		f:close()
		print("wrote " .. path)
	end
	return 0
end

if not FORMS_GEN_NO_MAIN then
	os.exit(Gen.run(arg or {}))
end

return Gen
